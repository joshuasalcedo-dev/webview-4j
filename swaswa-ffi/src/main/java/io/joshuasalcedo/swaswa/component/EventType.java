package io.joshuasalcedo.swaswa.component;

/** The DOM's events, typed: {@code on(EventType.DBLCLICK, ...)}. Any other by its name: {@link Component#on(String, Listener)}. */
public enum EventType {
    CLICK("click"),
    DBLCLICK("dblclick"),
    AUXCLICK("auxclick"),
    CONTEXTMENU("contextmenu"),
    MOUSEDOWN("mousedown"),
    MOUSEUP("mouseup"),
    MOUSEMOVE("mousemove"),
    MOUSEOVER("mouseover"),
    MOUSEOUT("mouseout"),
    MOUSEENTER("mouseenter"),
    MOUSELEAVE("mouseleave"),
    POINTERDOWN("pointerdown"),
    POINTERUP("pointerup"),
    POINTERMOVE("pointermove"),
    POINTEROVER("pointerover"),
    POINTEROUT("pointerout"),
    POINTERENTER("pointerenter"),
    POINTERLEAVE("pointerleave"),
    POINTERCANCEL("pointercancel"),
    GOTPOINTERCAPTURE("gotpointercapture"),
    LOSTPOINTERCAPTURE("lostpointercapture"),
    WHEEL("wheel"),
    KEYDOWN("keydown"),
    KEYUP("keyup"),
    BEFOREINPUT("beforeinput"),
    INPUT("input"),
    CHANGE("change"),
    FOCUS("focus"),
    BLUR("blur"),
    FOCUSIN("focusin"),
    FOCUSOUT("focusout"),
    SUBMIT("submit"),
    RESET("reset"),
    INVALID("invalid"),
    SELECT("select"),
    COPY("copy"),
    CUT("cut"),
    PASTE("paste"),
    DRAGSTART("dragstart"),
    DRAG("drag"),
    DRAGEND("dragend"),
    DRAGENTER("dragenter"),
    DRAGOVER("dragover"),
    DRAGLEAVE("dragleave"),
    DROP("drop"),
    TOUCHSTART("touchstart"),
    TOUCHMOVE("touchmove"),
    TOUCHEND("touchend"),
    TOUCHCANCEL("touchcancel"),
    SCROLL("scroll"),
    SCROLLEND("scrollend"),
    RESIZE("resize"),
    TOGGLE("toggle"),
    BEFORETOGGLE("beforetoggle"),
    LOAD("load"),
    ERROR("error"),
    ABORT("abort"),
    PLAY("play"),
    PAUSE("pause"),
    ENDED("ended"),
    TIMEUPDATE("timeupdate"),
    VOLUMECHANGE("volumechange"),
    LOADEDDATA("loadeddata"),
    LOADEDMETADATA("loadedmetadata"),
    CANPLAY("canplay"),
    SEEKING("seeking"),
    SEEKED("seeked"),
    RATECHANGE("ratechange"),
    ANIMATIONSTART("animationstart"),
    ANIMATIONEND("animationend"),
    ANIMATIONITERATION("animationiteration"),
    TRANSITIONSTART("transitionstart"),
    TRANSITIONEND("transitionend"),
    TRANSITIONRUN("transitionrun"),
    TRANSITIONCANCEL("transitioncancel"),
    CANCEL("cancel"),
    CLOSE("close"),
    FULLSCREENCHANGE("fullscreenchange");

    private final String dom;

    EventType(String dom) {
        this.dom = dom;
    }

    /** As the DOM names it: {@code dblclick}. */
    public String dom() {
        return dom;
    }
}
