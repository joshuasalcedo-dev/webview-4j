import java.io.IOException;
import java.nio.charset.StandardCharsets;
import java.nio.file.Files;
import java.nio.file.Path;
import java.util.ArrayList;
import java.util.Comparator;
import java.util.LinkedHashMap;
import java.util.List;
import java.util.Locale;
import java.util.Map;
import java.util.Set;
import java.util.stream.Stream;

/**
 * Writes HTML's elements as typed Java classes, one per element ({@code Div}, {@code A}, {@code Input}...), each an
 * {@code HtmlElement} with its own attributes as Swing-style setters and getters ({@code setHref(String)},
 * {@code getType()}, {@code isRequired()}), a word list as its enum, and an {@code Html} class of factories
 * ({@code Html.div(...)}, {@code Html.a("Docs")}).
 *
 * <p>Run by the build before compiling, as a single source file ({@code java HtmlJava.java <elements.json> <out>}):
 * no dependencies. The model ({@code src/build/html/elements.json}) lists the elements and their attributes as React's
 * types name them; the classes write the attributes as HTML does ({@code hrefLang} is {@code hreflang}).
 */
public class HtmlJava {

    static final String PACKAGE = "io.joshuasalcedo.swaswa.html";
    static final String HEADER = "// Generated by the build (src/build/HtmlJava.java) from src/build/html/elements.json: do not edit.\n";

    /** Methods every element has already: an attribute of the same name keeps its own with "Attribute" after it. */
    static final Set<String> TAKEN = Set.of("setText", "getText", "setEnabled", "isEnabled", "setVisible", "isVisible",
            "setToolTipText", "getToolTipText", "getComponents", "getComponentCount", "getTag", "setId", "getId",
            "setDraggable", "isDraggable");

    /** Only form controls hold what the user typed or picked. */
    static final Set<String> HOLDS_VALUE = Set.of("input", "textarea", "select");

    public static void main(String[] args) throws IOException {
        Path model = Path.of(args[0]);
        Path out = Path.of(args[1]).resolve(PACKAGE.replace('.', '/'));
        Path stamp = out.resolve(".from");
        String modelText = Files.readString(model, StandardCharsets.UTF_8);
        String key = Integer.toHexString(modelText.hashCode());
        if (Files.exists(stamp) && Files.readString(stamp).equals(key + "-" + selfStamp())) return;   // as it was made
        if (Files.exists(out)) try (Stream<Path> old = Files.walk(out)) {
            old.sorted(Comparator.reverseOrder()).forEach(p -> p.toFile().delete());
        }
        Files.createDirectories(out);

        @SuppressWarnings("unchecked")
        Map<String, Object> root = (Map<String, Object>) new Json(modelText).value();
        @SuppressWarnings("unchecked")
        List<Map<String, Object>> elements = (List<Map<String, Object>>) root.get("elements");
        @SuppressWarnings("unchecked")
        List<String> left = (List<String>) root.get("left");
        @SuppressWarnings("unchecked")
        List<String> deprecated = (List<String>) root.get("deprecated");

        StringBuilder factories = new StringBuilder();
        for (Map<String, Object> el : elements) {
            String tag = (String) el.get("tag");
            String cls = pascal(tag);
            boolean isVoid = Boolean.TRUE.equals(el.get("void"));
            @SuppressWarnings("unchecked")
            List<Map<String, Object>> attributes = (List<Map<String, Object>>) el.get("attributes");
            Files.writeString(out.resolve(cls + ".java"), element(tag, cls, (String) el.get("dom"), isVoid, attributes), StandardCharsets.UTF_8);
            String m = tag.equals("var") ? "var_" : tag;
            if (isVoid) {
                factories.append("    /** {@code <").append(tag).append(">}. */\n    public static ").append(cls).append(' ').append(m)
                        .append("() { return new ").append(cls).append("(); }\n\n");
            } else {
                factories.append("    /** {@code <").append(tag).append(">} holding these. */\n    public static ").append(cls).append(' ').append(m)
                        .append("(Node... children) { return new ").append(cls).append("().add(children); }\n");
                factories.append("    /** {@code <").append(tag).append(">} holding this text. */\n    public static ").append(cls).append(' ').append(m)
                        .append("(String text) { return new ").append(cls).append("().setText(text); }\n\n");
            }
        }
        String html = HEADER + "package " + PACKAGE + ";\n\n"
                + "/**\n * HTML's elements, typed: {@code Html.div(Html.p(\"Paid\"))},\n"
                + " * {@code Html.input().setType(Input.Type.EMAIL).setRequired(true)}, {@code Html.a(\"Docs\").setHref(\"https://...\")}.\n"
                + " * Each is an {@link HtmlElement}: global attributes, CSS classes, a style, listeners, children.\n"
                + " * <p>Left out: deprecated and non-standard elements (" + String.join(", ", deprecated) + "); on purpose: "
                + doc(String.join("; ", left)) + ".\n */\n"
                + "public final class Html {\n\n    private Html() {}\n\n"
                + "    /** Text beside other children: {@code Html.p(Html.text(\"Paid on \"), Html.strong(\"Monday\"))}. */\n"
                + "    public static Text text(String text) { return new Text(text); }\n\n"
                + factories + "}\n";
        Files.writeString(out.resolve("Html.java"), html, StandardCharsets.UTF_8);
        Files.writeString(stamp, key + "-" + selfStamp());
        System.out.println("HtmlJava: " + elements.size() + " elements into " + out);
    }

    /** Changes when this generator does: its classes are made again. */
    /** The URL attributes only ever loaded as an image (where an SVG cannot run script): Class.attribute. */
    static final java.util.Set<String> IMAGES = java.util.Set.of("Img.src", "Input.src", "Video.poster");

    /** The elements that are a role's (a button, a text input, a choice): they implement it, as every library's do. */
    static final Map<String, String> ROLES = Map.ofEntries(
            Map.entry("Button", "ButtonBase"), Map.entry("Label", "Labeled"),
            Map.entry("Input", "TextField"), Map.entry("Textarea", "TextArea"),
            Map.entry("Select", "Choice"), Map.entry("Option", "ChoiceOption"), Map.entry("Datalist", "ComboBox"),
            Map.entry("Data", "DataValue"), Map.entry("Dialog", "DialogBase"), Map.entry("Details", "Disclosure"),
            Map.entry("Progress", "ProgressIndicator"), Map.entry("Meter", "ProgressIndicator"), Map.entry("Table", "TableView"),
            Map.entry("Menu", "MenuBase"), Map.entry("Nav", "Navigation"), Map.entry("Hr", "Separator"), Map.entry("Img", "ImageView"),
            Map.entry("Kbd", "KeyboardKey"), Map.entry("Code", "CodeView"), Map.entry("Pre", "CodeView"),
            Map.entry("Ul", "ListView"), Map.entry("Ol", "ListView"), Map.entry("Li", "ListItem"), Map.entry("A", "Hyperlink"),
            Map.entry("Form", "FormBase"), Map.entry("Fieldset", "FieldGroup"), Map.entry("Audio", "MediaView"),
            Map.entry("Video", "MediaView"));

    static String selfStamp() {
        return "10";
    }

    /** React's name as HTML writes it: {@code hrefLang} is {@code hreflang}, {@code htmlFor} {@code for}. */
    static String htmlName(String react) {
        return switch (react) {
            case "htmlFor" -> "for";
            case "acceptCharset" -> "accept-charset";
            case "httpEquiv" -> "http-equiv";
            case "className" -> "class";
            default -> react.contains("-") ? react : react.toLowerCase(Locale.ROOT);
        };
    }

    static String element(String tag, String cls, String dom, boolean isVoid, List<Map<String, Object>> attributes) {
        StringBuilder b = new StringBuilder(HEADER);
        b.append("package ").append(PACKAGE).append(";\n\n");
        b.append("/** {@code <").append(tag).append(">} ({@code ").append(dom)
                .append("}): <a href=\"https://developer.mozilla.org/en-US/docs/Web/HTML/Reference/Elements/").append(tag).append("\">MDN</a>. */\n");
        // open, as Swing's JPanel: a panel of one's own extends Div
        b.append("public class ").append(cls).append(" extends HtmlElement<").append(cls).append(">");
        String role = ROLES.get(cls);   // the role every library's control of this kind shares (component.ButtonBase...)
        if (role != null) b.append(" implements io.joshuasalcedo.swaswa.component.").append(role).append('<').append(cls).append('>');
        b.append(" {\n\n");
        b.append("    public ").append(cls).append("() {\n        super(\"").append(tag).append("\", ").append(isVoid).append(");\n");
        if (HOLDS_VALUE.contains(tag)) {
            b.append("        // what the user types or picks: the page holds it, and it is kept here before any listener\n");
            b.append("        hold(\"value\");\n");
            if (tag.equals("input")) b.append("        hold(\"checked\");\n");
        }
        if (tag.equals("details") || tag.equals("dialog")) b.append("        hold(\"open\");\n");
        b.append("    }\n");
        if (!isVoid) {
            // as Swing's: new JButton("Save"); new JPanel(), then add(...)
            b.append("\n    /** {@code <").append(tag).append(">} holding this text: {@code new ").append(cls).append("(\"...\")}. */\n");
            b.append("    public ").append(cls).append("(String text) {\n        this();\n        setText(text);\n    }\n");
            b.append("\n    /** {@code <").append(tag).append(">} holding these. */\n");
            b.append("    public ").append(cls).append("(Node... children) {\n        this();\n        add(children);\n    }\n");
        }

        Map<String, String> used = new LinkedHashMap<>();
        for (Map<String, Object> a : attributes) attribute(b, cls, a, used);

        if (HOLDS_VALUE.contains(tag)) {
            b.append("""

                        /** What the user typed or picked, as it is now in the page. */
                        public String getValue() { return held("value"); }

                        /** Sets what it holds: the page shows it. */
                        public %1$s setValue(String value) { return setHeld("value", value); }

                        /** What it holds, as a property: to listen to or bind ({@code a.valueProperty().bindBidirectional(b.valueProperty())}). */
                        public io.joshuasalcedo.swaswa.component.Property<String> valueProperty() { return heldProperty("value"); }
                    """.formatted(cls));
        }
        if (tag.equals("input")) {
            b.append("""

                        /** Whether a check box or radio button is checked, as it is now in the page. */
                        public boolean isChecked() { return "true".equals(held("checked")); }

                        public Input setChecked(boolean checked) { return setHeld("checked", checked ? "true" : null); }

                        /** It was checked or unchecked (a check box, a radio button): {@link #isChecked()} says which. */
                        public Input addItemListener(io.joshuasalcedo.swaswa.component.Listener listener) { return on("change", listener); }

                        public Input removeItemListener(io.joshuasalcedo.swaswa.component.Listener listener) { return off("change", listener); }
                    """);
        }
        if (tag.equals("form")) {
            b.append("""

                        /**
                         * It was submitted (the page does not leave): the event's {@link HtmlEvent#fields()} has the
                         * fields by name.
                         */
                        public Form addSubmitListener(io.joshuasalcedo.swaswa.component.Listener listener) { return on("submit", listener); }

                        public Form removeSubmitListener(io.joshuasalcedo.swaswa.component.Listener listener) { return off("submit", listener); }
                    """);
        }
        if (tag.equals("details") || tag.equals("dialog")) {
            b.append("""

                        /** Whether it is open, as it is now in the page. */
                        public boolean isOpen() { return "true".equals(held("open")); }

                        public %1$s setOpen(boolean open) { return setHeld("open", open ? "true" : null); }

                        /** It opened or closed: {@link #isOpen()} says which. */
                        public %1$s addToggleListener(io.joshuasalcedo.swaswa.component.Listener listener) { return on("toggle", listener); }

                        public %1$s removeToggleListener(io.joshuasalcedo.swaswa.component.Listener listener) { return off("toggle", listener); }
                    """.formatted(cls));
        }
        if (tag.equals("dialog")) {
            b.append("""

                        /** Shows it over the page, everything else inert until it closes ({@code showModal()}). */
                        public Dialog showModal() { setHeldQuietly("open", "true"); return call("showModal"); }

                        /** Closes it ({@code close()}). */
                        public Dialog close() { setHeldQuietly("open", null); return call("close"); }
                    """);
        }
        b.append("}\n");
        return b.toString();
    }

    static void attribute(StringBuilder b, String cls, Map<String, Object> a, Map<String, String> used) {
        String react = (String) a.get("name");
        String html = htmlName(react);
        if (html.equals("value") || html.equals("checked") || html.equals("open")) return;   // held: getValue / setValue above
        String base = pascal(react);
        if (TAKEN.contains("set" + base) || TAKEN.contains("get" + base) || TAKEN.contains("is" + base)) base = base + "Attribute";
        if (used.containsKey(base)) throw new IllegalStateException(cls + ": two attributes make " + base + ": " + used.get(base) + ", " + react);
        used.put(base, react);
        boolean text = Boolean.TRUE.equals(a.get("text"));
        boolean number = Boolean.TRUE.equals(a.get("number"));
        boolean bool = Boolean.TRUE.equals(a.get("bool"));
        boolean list = Boolean.TRUE.equals(a.get("list"));
        boolean url = Boolean.TRUE.equals(a.get("url"));
        boolean image = IMAGES.contains(cls + "." + html);   // a URL only ever loaded as an image: SVG is fine there
        @SuppressWarnings("unchecked")
        List<String> words = (List<String>) a.get("words");
        String about = "{@code " + html + "}" + (a.get("doc") instanceof String d && !d.isBlank() ? ": " + doc(d) : "");
        b.append('\n');

        String enumName = null;
        if (!words.isEmpty()) {
            enumName = base.equals(cls) ? base + "Value" : base;
            b.append("    /** {@code ").append(html).append("}'s words. */\n");
            b.append("    public enum ").append(enumName).append(" implements HtmlLiteral {\n");
            Map<String, String> constants = new LinkedHashMap<>();
            for (String w : words) constants.putIfAbsent(constant(w), w);
            List<String> lines = new ArrayList<>();
            constants.forEach((k, w) -> lines.add("        " + k + "(\"" + w.replace("\\", "\\\\").replace("\"", "\\\"") + "\")"));
            b.append(String.join(",\n", lines)).append(";\n\n");
            b.append("        private final String literal;\n        ").append(enumName).append("(String literal) { this.literal = literal; }\n");
            b.append("        @Override public String literal() { return literal; }\n    }\n\n");
            b.append("    /** ").append(about).append(" */\n");
            b.append("    public ").append(cls).append(" set").append(base).append('(').append(enumName).append(" value) { return attribute(\"")
                    .append(html).append("\", value == null ? null : value.literal()); }\n");
        }
        if (text) {
            b.append("    /** ").append(about).append(" */\n");
            b.append("    public ").append(cls).append(" set").append(base).append("(String value) { return attribute(\"").append(html)
                    .append("\", ").append(image ? "imageUrl(value)" : url ? "url(value)" : "value").append("); }\n");
        }
        if (number) {
            b.append("    public ").append(cls).append(" set").append(base).append("(double value) { return attribute(\"").append(html).append("\", number(value)); }\n");
        }
        if (bool) {
            b.append("    public ").append(cls).append(" set").append(base).append("(boolean value) { return flag(\"").append(html).append("\", value); }\n");
        }
        if (list && !text) {
            b.append("    public ").append(cls).append(" set").append(base).append("(String... values) { return attribute(\"").append(html)
                    .append("\", String.join(\" \", values)); }\n");
        }
        if (enumName != null && text) {
            // its words typed, and any other text as written
            b.append("    public ").append(enumName).append(" get").append(base).append("() { return literal(\"").append(html).append("\", ").append(enumName).append(".class); }\n");
            b.append("    public String get").append(base).append("Text() { return getAttribute(\"").append(html).append("\"); }\n");
        } else if (text) b.append("    public String get").append(base).append("() { return getAttribute(\"").append(html).append("\"); }\n");
        else if (enumName != null) b.append("    public ").append(enumName).append(" get").append(base).append("() { return literal(\"").append(html).append("\", ").append(enumName).append(".class); }\n");
        else if (number) b.append("    public Double get").append(base).append("() { return numberOf(\"").append(html).append("\"); }\n");
        else if (bool) b.append("    public boolean is").append(base).append("() { return hasAttribute(\"").append(html).append("\"); }\n");
    }

    /** {@code div} is {@code Div}; {@code hrefLang} {@code HrefLang}; {@code h1} {@code H1}. */
    static String pascal(String name) {
        StringBuilder b = new StringBuilder();
        for (String part : name.split("[^A-Za-z0-9]+")) {
            if (part.isEmpty()) continue;
            b.append(Character.toUpperCase(part.charAt(0))).append(part.substring(1));
        }
        return b.toString();
    }

    /** {@code no-referrer} is {@code NO_REFERRER}; {@code _blank} {@code BLANK}; {@code 1} {@code V_1}. */
    static String constant(String word) {
        String c = word.replaceAll("([a-z0-9])([A-Z])", "$1_$2").replaceAll("[^A-Za-z0-9]+", "_").replaceAll("^_|_$", "").toUpperCase(Locale.ROOT);
        return c.isEmpty() || Character.isDigit(c.charAt(0)) ? "V_" + c : c;
    }

    static String doc(String text) {
        return text.replace("&", "&amp;").replace("<", "&lt;").replace(">", "&gt;").replace("*/", "*&#47;").replace("@", "&#64;");
    }

    /** Just enough JSON to read the model: objects, arrays, strings, numbers, true, false, null. */
    static final class Json {
        private final String s;
        private int i;

        Json(String s) { this.s = s; }

        Object value() {
            space();
            char c = s.charAt(i);
            if (c == '{') {
                Map<String, Object> m = new LinkedHashMap<>();
                i++;
                space();
                if (s.charAt(i) == '}') { i++; return m; }
                while (true) {
                    space();
                    String k = string();
                    space();
                    i++; // :
                    m.put(k, value());
                    space();
                    if (s.charAt(i++) == '}') return m;
                }
            }
            if (c == '[') {
                List<Object> l = new ArrayList<>();
                i++;
                space();
                if (s.charAt(i) == ']') { i++; return l; }
                while (true) {
                    l.add(value());
                    space();
                    if (s.charAt(i++) == ']') return l;
                }
            }
            if (c == '"') return string();
            if (s.startsWith("true", i)) { i += 4; return true; }
            if (s.startsWith("false", i)) { i += 5; return false; }
            if (s.startsWith("null", i)) { i += 4; return null; }
            int start = i;
            while (i < s.length() && "+-0123456789.eE".indexOf(s.charAt(i)) >= 0) i++;
            return Double.parseDouble(s.substring(start, i));
        }

        private String string() {
            StringBuilder b = new StringBuilder();
            i++; // "
            while (true) {
                char c = s.charAt(i++);
                if (c == '"') return b.toString();
                if (c != '\\') { b.append(c); continue; }
                char e = s.charAt(i++);
                switch (e) {
                    case 'n' -> b.append('\n');
                    case 't' -> b.append('\t');
                    case 'r' -> b.append('\r');
                    case 'b' -> b.append('\b');
                    case 'f' -> b.append('\f');
                    case 'u' -> { b.append((char) Integer.parseInt(s.substring(i, i + 4), 16)); i += 4; }
                    default -> b.append(e);
                }
            }
        }

        private void space() {
            while (i < s.length() && Character.isWhitespace(s.charAt(i))) i++;
        }
    }
}
