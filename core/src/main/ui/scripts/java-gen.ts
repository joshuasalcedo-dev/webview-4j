// java-gen: Java classes for React components, read from their props with TypeScript's own type checker.
//
//   bun run java-gen          writes them
//   bun run java-gen:check    fails if what is written is not what the components give (the build runs it)
//
// Only the components java-gen.json names are made. For each one it writes
//   - core/src/main/java/io/joshuasalcedo/webview4j/ui/components/<Java>.java, the class Java screens use;
//   - its case in src/java-ui.generated.tsx, which java-ui.tsx asks only for types it has no case of its own for.
// It never touches a hand-written class (a file without the generated header), nor a type java-ui.tsx already
// draws: either stops it with an error. What it cannot map (a prop holding a function inside an object, a ref...)
// it leaves out and says so.

import * as fs from "node:fs"
import * as path from "node:path"
import * as process from "node:process"
import ts from "typescript"

const UI = path.resolve(import.meta.dirname, "..")
const JAVA_DIR = path.resolve(UI, "../java/io/joshuasalcedo/webview4j/ui/components")
const MANIFEST = path.join(UI, "java-gen.json")
const RENDERER = path.join(UI, "src/java-ui.tsx")
const GENERATED_TSX = path.join(UI, "src/java-ui.generated.tsx")
const HEADER = "// Generated by core/src/main/ui/scripts/java-gen.ts"

type Entry = {
  /** The node type Java sends and the renderer switches on, e.g. "emptyState". */
  type: string
  /** The exported React component. */
  component: string
  /** Its file, from core/src/main/ui. */
  from: string
  /** The Java class, in io.joshuasalcedo.webview4j.ui.components. */
  java: string
  /** Props to leave out on purpose. */
  skip?: string[]
  /** Loaded the first time a screen shows one (a large library: charts), not with the kit. */
  lazy?: boolean
}

/** What a prop is, as far as Java and the renderer care. */
type Kind =
  | { k: "string" }
  | { k: "number" }
  | { k: "boolean" }
  | { k: "enum"; values: string[] }
  | { k: "multi"; kinds: ("string" | "number" | "boolean")[] }
  | { k: "node"; text: boolean }
  | { k: "callback"; arg: "none" | "string" | "number" | "boolean" | "json" }
  /** An object argument with parts Java cannot get (File[]): only `keys` go. */
  | { k: "callback"; arg: "pick"; keys: string[] }
  /** Several arguments, as a list: those Java cannot get go as null. */
  | { k: "callback"; arg: "args"; mask: boolean[] }
  | { k: "data"; ts: string }

/** `jt`: a data prop's Java type (a generated record, a List, an enum...). */
type Prop = { name: string; java: string; kind: Kind; required: boolean; doc: string; jt?: string }
/** `types`: the records, enums and sealed interfaces a component's data props are made of, as Java. */
type Model = { entry: Entry; doc: string; props: Prop[]; children: boolean; style: boolean; left: string[]; types: string[] }

/** Where the Java types for one component's data are gathered while its props are read. */
type TypeContext = { checker: ts.TypeChecker; owner: string; decls: string[]; byType: Map<ts.Type, string>; names: Set<string> }

