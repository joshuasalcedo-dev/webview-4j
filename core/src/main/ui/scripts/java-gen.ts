function fail(message: string): never {
  console.error(`java-gen: ${message}`)
  process.exit(1)
}

// ---------------------------------------------------------------- reading the components

function program(): ts.Program {
  const configPath = path.join(UI, "tsconfig.json")
  const parsed = ts.getParsedCommandLineOfConfigFile(configPath, {}, {
    ...ts.sys,
    onUnRecoverableConfigFileDiagnostic: (d) => fail(ts.flattenDiagnosticMessageText(d.messageText, "\n")),
  })
  if (!parsed) fail("cannot read tsconfig.json")
  // Only the components' files are needed (their imports come along): much faster than the whole kit.
  const manifest = readManifest()
  return ts.createProgram(manifest.map((e) => path.join(UI, e.from)), parsed.options)
}

function readManifest(): Entry[] {
  const json = JSON.parse(fs.readFileSync(MANIFEST, "utf8")) as { components: Entry[] }
  const seen = new Set<string>()
  for (const e of json.components) {
    for (const field of ["type", "component", "from", "java"] as const)
      if (typeof e[field] !== "string" || !e[field]) fail(`java-gen.json: an entry has no "${field}"`)
    if (!/^[A-Z][A-Za-z0-9]*$/.test(e.java)) fail(`java-gen.json: "${e.java}" is not a Java class name`)
    if (!/^[a-z][A-Za-z0-9]*$/.test(e.type)) fail(`java-gen.json: "${e.type}" is not a node type (camelCase)`)
    if (seen.has(e.type) || seen.has(e.java)) fail(`java-gen.json: "${e.type}" / "${e.java}" twice`)
    seen.add(e.type)
    seen.add(e.java)
  }
  return json.components
}

/** The node types java-ui.tsx draws by hand: a generated one must not take their place. */
function handWrittenTypes(): Set<string> {
  const source = fs.readFileSync(RENDERER, "utf8")
  return new Set([...source.matchAll(/case "([^"]+)":/g)].map((m) => m[1]))
}

function isOwn(symbol: ts.Symbol): boolean {
  const declarations = symbol.getDeclarations() ?? []
  return declarations.length > 0 && declarations.every((d) => !d.getSourceFile().fileName.includes("node_modules"))
}

function docOf(symbol: ts.Symbol, checker: ts.TypeChecker): string {
  return ts.displayPartsToString(symbol.getDocumentationComment(checker)).trim()
}

function members(type: ts.Type): ts.Type[] {
  return type.isUnion() ? type.types : [type]
}

function withoutNullish(type: ts.Type): ts.Type[] {
  return members(type).filter((t) => !(t.flags & (ts.TypeFlags.Undefined | ts.TypeFlags.Null | ts.TypeFlags.Void)))
}

function isReactNode(type: ts.Type, checker: ts.TypeChecker): boolean {
  const text = checker.typeToString(type)
  if (type.aliasSymbol?.name === "ReactNode" || /^(React\.)?ReactNode$/.test(text)) return true
  return members(type).some((t) => /ReactElement|ReactPortal|JSX\.Element/.test(checker.typeToString(t)))
}

/**
 * JSON all the way down (no functions, no React nodes): what Java can send as records, lists and maps. Inside an
 * object, an optional member that is not JSON (a ReactNode icon, an onUnlock) is fine: Java leaves it out.
 */
function isData(type: ts.Type, checker: ts.TypeChecker, depth = 0): boolean {
  if (depth > 6) return true
  const parts = withoutNullish(type)
  if (parts.length === 0) return true
  for (const t of parts) {
    if (t.flags & (ts.TypeFlags.StringLike | ts.TypeFlags.NumberLike | ts.TypeFlags.BooleanLike)) continue
    if (t.getCallSignatures().length > 0) return false
    if (isReactNode(t, checker)) return false
    if (checker.typeToString(t) === "Date") continue // Java sends it as an ISO string
    if (checker.isArrayType(t) || checker.isTupleType(t)) {
      const args = checker.getTypeArguments(t as ts.TypeReference)
      if (!args.every((a) => isData(a, checker, depth + 1))) return false
      continue
    }
    if (t.flags & ts.TypeFlags.Object) {
      for (const p of checker.getPropertiesOfType(t)) {
        if (p.flags & ts.SymbolFlags.Optional) continue
        if (!isData(checker.getTypeOfSymbol(p), checker, depth + 1)) return false
      }
      const index = checker.getIndexInfosOfType(t)
      if (!index.every((i) => isData(i.type, checker, depth + 1))) return false
      continue
    }
    if (t.flags & (ts.TypeFlags.Any | ts.TypeFlags.Unknown)) continue
    return false
  }
  return true
}

function primitive(t: ts.Type): "string" | "number" | "boolean" | undefined {
  if (t.flags & ts.TypeFlags.StringLike) return "string"
  if (t.flags & ts.TypeFlags.NumberLike) return "number"
  if (t.flags & ts.TypeFlags.BooleanLike) return "boolean"
  return undefined
}

/** An event only returns nothing (or a promise of nothing): a function whose result is used Java cannot answer. */
function returnsNothing(sig: ts.Signature, checker: ts.TypeChecker): boolean {
  const nothing = (t: ts.Type) => !!(t.flags & (ts.TypeFlags.Void | ts.TypeFlags.Undefined | ts.TypeFlags.Any | ts.TypeFlags.Unknown))
  return members(sig.getReturnType()).every((t) => {
    if (nothing(t)) return true
    if (t.getSymbol()?.name === "Promise") return checker.getTypeArguments(t as ts.TypeReference).every((a) => members(a).every(nothing))
    return false
  })
}

function callbackArg(sig: ts.Signature, checker: ts.TypeChecker): (Kind & { k: "callback" }) | undefined {
  if (!returnsNothing(sig, checker)) return undefined
  const params = sig.getParameters()
  if (params.length === 0) return { k: "callback", arg: "none" }
  if (params.length > 1) {
    const mask = params.map((p) => isData(checker.getTypeOfSymbol(p), checker))
    return mask.some(Boolean) ? { k: "callback", arg: "args", mask } : { k: "callback", arg: "none" }
  }
  const type = checker.getTypeOfSymbol(params[0])
  const kinds = new Set(withoutNullish(type).map(primitive))
  if (kinds.size === 1 && !kinds.has(undefined)) return { k: "callback", arg: [...kinds][0]! }
  if (isData(type, checker)) return { k: "callback", arg: "json" }
  // An object with some parts that are JSON ({ text, files }): those parts.
  const parts = withoutNullish(type)
  if (parts.length === 1 && parts[0].flags & ts.TypeFlags.Object && parts[0].getCallSignatures().length === 0) {
    const keys = checker.getPropertiesOfType(parts[0]).filter((p) => isData(checker.getTypeOfSymbol(p), checker)).map((p) => p.name)
    if (keys.length) return { k: "callback", arg: "pick", keys }
  }
  return { k: "callback", arg: "none" }
}

function kindOf(type: ts.Type, checker: ts.TypeChecker): Kind | undefined {
  if (isReactNode(type, checker)) return { k: "node", text: true }
  return kindOfParts(withoutNullish(type), checker)
}

/** The kind of a union's members (null and undefined taken out). */
function kindOfParts(parts: ts.Type[], checker: ts.TypeChecker): Kind | undefined {
  if (parts.length === 0) return undefined
  // A function, or a function or its result (menu: MenuEntry[] | (() => MenuEntry[])): the data side wins.
  const calls = parts.filter((t) => t.getCallSignatures().length > 0)
  const rest = parts.filter((t) => t.getCallSignatures().length === 0)
  if (calls.length > 0 && rest.length === 0) return callbackArg(calls[0].getCallSignatures()[0], checker)
  if (calls.length > 0) return kindOfParts(rest, checker)

  if (parts.some((t) => isReactNode(t, checker))) return { k: "node", text: true }

  // `boolean` is `true | false`: fold the literals back.
  const literalStrings = parts.filter((t) => t.isStringLiteral()) as ts.StringLiteralType[]
  const allBooleans = parts.every((t) => t.flags & ts.TypeFlags.BooleanLike)
  if (allBooleans) return { k: "boolean" }
  if (literalStrings.length === parts.length) return { k: "enum", values: literalStrings.map((t) => t.value) }

  const prims = new Set(parts.map(primitive))
  if (!prims.has(undefined)) {
    if (prims.size === 1) return { k: [...prims][0]! }
    return { k: "multi", kinds: (["string", "number", "boolean"] as const).filter((p) => prims.has(p)) }
  }
  // string | Date and the like: Java sends the string.
  if (prims.has("string") && parts.every((t) => primitive(t) || checker.typeToString(t) === "Date")) return { k: "string" }

  if (parts.every((t) => isData(t, checker)))
    return { k: "data", ts: parts.map((t) => checker.typeToString(t, undefined, ts.TypeFormatFlags.NoTruncation)).join(" | ") }
  return undefined
}

// ---------------------------------------------------------------- data as Java types

const boxed = (t: string) => ({ double: "Double", boolean: "Boolean", long: "Long", int: "Integer" })[t] ?? t
const asParam = (t: string) => t.replace(/^java\.util\.List<Object>$/, "java.util.List<?>")
const singular = (s: string) => (s.endsWith("ies") ? s.slice(0, -3) + "y" : s.endsWith("s") && !s.endsWith("ss") ? s.slice(0, -1) : s)

/**
 * The types the kit's components share: one Java file each in ui.components (ChatTag, Conversation...), made the
 * first time a component needs one; the hand-written ones (PillColor) are used as they are.
 */
const SHARED = {
  byType: new Map<ts.Type, string>(),
  files: new Map<string, string>(),
  /** The hand-written classes in ui.components, by name: their text. */
  handWritten: new Map<string, string>(),
  /** Names no shared type may take: the components', the hand-written classes'. */
  reserved: new Set<string>(),
}

/** TypeScript's own name for a type (an alias, an interface), or the one its prop declares it with. */
function declaredName(type: ts.Type, declared?: string): string | undefined {
  if (type.aliasSymbol && !type.aliasTypeArguments?.length) return type.aliasSymbol.name
  if (type.symbol && type.symbol.flags & (ts.SymbolFlags.Interface | ts.SymbolFlags.Class)) return type.symbol.name
  return declared
}

/** The Java name of a shared type: TypeScript's, unless a component or a hand-written class has it ("Data" after). */
function sharedName(name: string): string {
  let n = up(javaName(name))
  if (JAVA_LANG.has(n) || SHARED.reserved.has(n)) n = `${n}Data`
  return n
}

function sharedFile(code: string, source: string): string {
  return `${HEADER} from ${source} (a type the kit's components share): do not edit.
// Change it in TypeScript, then run \`bun run java-gen\` in core/src/main/ui.
package io.joshuasalcedo.webview4j.ui.components;

import io.joshuasalcedo.webview4j.JsonValue;

${code}
`
}

/** A free Java name for a nested type, from TypeScript's name for it, or from where it is (its prop). */
function typeName(type: ts.Type, ctx: TypeContext, hint: string): string {
  const alias = type.aliasSymbol && !type.aliasTypeArguments?.length ? type.aliasSymbol.name : undefined
  const own = type.symbol && !["__type", "__object", "Object"].includes(type.symbol.name) ? type.symbol.name : undefined
  let name = up(javaName(alias ?? own ?? hint))
  if (name === ctx.owner || JAVA_LANG.has(name)) name = `${name}Value`
  let n = name
  const taken = (x: string) => ctx.names.has(x) || SHARED.files.has(x) || SHARED.reserved.has(x)
  for (let i = 2; taken(n); i++) n = `${name}${i}`
  ctx.names.add(n)
  return n
}

const JAVA_LANG = new Set(["Object", "String", "Record", "Class", "Boolean", "Double", "Integer", "Long", "Number", "Enum", "List", "Map", "Optional", "Component", "Consumer", "Keys", "JsonValue"])

/**
 * The Java type for a TypeScript data type: String, Double, Boolean, an enum for a string union, a record for an
 * object, a sealed interface for a union of objects told apart by one field ({ kind: "image" | "file" ...}),
 * java.util.List for an array, java.util.Map for an object of any keys; Object only for "any value" (a row of
 * any record: it takes the app's own records) and for a mix of plain values (boolean | string).
 */
function javaTypeOf(type: ts.Type, ctx: TypeContext, hint: string, required = false, declared?: string): string {
  const { checker } = ctx
  const data = withoutNullish(type).filter((t) => t.getCallSignatures().length === 0 && !isReactNode(t, checker))
  if (data.length === 0) return "Object"
  const known = data.length === 1 ? ctx.byType.get(data[0]) : undefined
  if (known) return known
  if (data.every((t) => t.flags & ts.TypeFlags.BooleanLike)) return required ? "boolean" : "Boolean"
  if (data.every((t) => t.isStringLiteral())) return enumOf(data as ts.StringLiteralType[], type, ctx, hint, declared)
  const prims = new Set(data.map(primitive))
  if (!prims.has(undefined)) {
    if (prims.size > 1) return "Object" // a mix (boolean | string): either goes
    const p = [...prims][0]
    return p === "string" ? "String" : p === "number" ? (required ? "double" : "Double") : required ? "boolean" : "Boolean"
  }
  if (prims.has("string") && data.every((t) => primitive(t) || checker.typeToString(t) === "Date")) return "String"
  if (data.length === 1) {
    const t = data[0]
    if (t.isIntersection()) {
      // a branded number or string (MinorUnits): the plain value
      const p = t.types.map(primitive).find(Boolean)
      if (p) return p === "string" ? "String" : p === "number" ? (required ? "double" : "Double") : "Boolean"
    }
    if (t.flags & (ts.TypeFlags.Any | ts.TypeFlags.Unknown)) return "Object"
    // a date goes from Java as ISO text ("2026-11-25T09:00:00Z")
    if (checker.typeToString(t) === "Date") return "String"
    if (checker.isTupleType(t)) return "java.util.List<Object>"
    if (checker.isArrayType(t)) {
      const element = checker.getTypeArguments(t as ts.TypeReference)[0]
      return `java.util.List<${boxed(javaTypeOf(element, ctx, singular(hint), false, declared))}>`
    }
    if (t.flags & ts.TypeFlags.Object) {
      const props = checker.getPropertiesOfType(t)
      const index = checker.getIndexInfosOfType(t)
      if (props.length === 0 && index.length) {
        const value = boxed(javaTypeOf(index[0].type, ctx, `${hint}Value`))
        // any keys, any values: a row of the app's own record, or a map
        return value === "Object" ? "Object" : `java.util.Map<String, ${value}>`
      }
      if (props.length === 0) return "Object"
      return recordOf(t, ctx, hint, declared)
    }
  }
  if (data.every((t) => t.flags & ts.TypeFlags.Object && !checker.isArrayType(t))) {
    const sealed = sealedOf(data, type, ctx, hint, declared)
    if (sealed) return sealed
  }
  return "Object"
}

function enumCode(E: string, values: ts.StringLiteralType[], indent: string, doc: string): string {
  return (
    javadoc(doc, indent, doc ? "" : "The page's words for it, in Java.") +
    `${indent}public enum ${E} implements JsonValue {\n` +
    values.map((v) => `${indent}    ${constant(v.value)}("${v.value}")`).join(",\n") +
    `;\n\n${indent}    final String key;\n\n${indent}    ${E}(String key) { this.key = key; }\n\n${indent}    @Override public Object json() { return key; }\n${indent}}`
  )
}

function enumOf(values: ts.StringLiteralType[], type: ts.Type, ctx: TypeContext, hint: string, declared?: string): string {
  const share = declaredName(type, declared)
  if (share) {
    const known = SHARED.byType.get(type)
    if (known) return known
    const plain = up(javaName(share))
    // a hand-written enum of the same name and the same words (PillColor): that one, not a copy
    const written = SHARED.handWritten.get(plain)
    if (written && /implements\s+JsonValue/.test(written) && values.every((v) => new RegExp(`\\b${constant(v.value)}\\b`).test(written))) {
      SHARED.byType.set(type, plain)
      return plain
    }
    if (written && /\benum\b/.test(written) && /implements\s+JsonValue/.test(written))
      fail(`${plain}.java (hand-written) lacks some of TypeScript's ${share}: ${values.map((v) => v.value).join(", ")}`)
    const E = sharedName(share)
    SHARED.byType.set(type, E)
    const doc = type.aliasSymbol ? docOf(type.aliasSymbol, ctx.checker) : ""
    SHARED.files.set(E, sharedFile(enumCode(E, values, "", doc), share))
    return E
  }
  const E = typeName(type, ctx, hint)
  ctx.byType.set(type, E)
  ctx.decls.push(enumCode(E, values, "    ", ""))
  return E
}

type Field = { name: string; java: string; type: string; required: boolean; doc: string }

/**
 * The name a property's type is declared with ("color?: PillColor" gives PillColor), else the property's own: an
 * optional prop's type loses its alias name once undefined is in the union.
 */
function hintOf(p: ts.Symbol): string {
  return up(javaName(declaredOf(p) ?? p.name))
}

/** The type name a property is declared with ("color?: PillColor", "tags?: ChatTag[]"), if it names one. */
function declaredOf(p: ts.Symbol): string | undefined {
  const decl = p.valueDeclaration
  const node = decl && (ts.isPropertySignature(decl) || ts.isPropertyDeclaration(decl)) ? decl.type : undefined
  const named = (n: ts.TypeNode | undefined): string | undefined =>
    !n ? undefined
    : ts.isTypeReferenceNode(n) && !n.typeArguments?.length ? n.typeName.getText().split(".").pop()
    : ts.isArrayTypeNode(n) ? named(n.elementType)
    : ts.isUnionTypeNode(n) ? n.types.map(named).find(Boolean)
    : ts.isParenthesizedTypeNode(n) ? named(n.type)
    : undefined
  return named(node)
}

/** The fields that can only ever be one word ({ kind: "voice" }): the record writes them, nobody passes them. */
function constantsOf(t: ts.Type, ctx: TypeContext): [string, string][] {
  return ctx.checker
    .getPropertiesOfType(t)
    .filter((p) => !(p.flags & ts.SymbolFlags.Optional))
    .map((p) => [p.name, withoutNullish(ctx.checker.getTypeOfSymbol(p))] as const)
    .filter(([, parts]) => parts.length === 1 && parts[0].isStringLiteral())
    .map(([name, parts]) => [name, (parts[0] as ts.StringLiteralType).value])
}

function fieldsOf(t: ts.Type, ctx: TypeContext, skip?: string): Field[] {
  const fields: Field[] = []
  const constants = new Set(constantsOf(t, ctx).map(([name]) => name))
  for (const p of ctx.checker.getPropertiesOfType(t)) {
    if (p.name === skip || constants.has(p.name)) continue
    const pt = ctx.checker.getTypeOfSymbol(p)
    const required = !(p.flags & ts.SymbolFlags.Optional)
    // what Java cannot give (a ReactNode icon, an onUnlock) was optional: left out
    if (!isData(pt, ctx.checker)) continue
    fields.push({ name: p.name, java: javaName(p.name), type: javaTypeOf(pt, ctx, hintOf(p), required, declaredOf(p)), required, doc: docOf(p, ctx.checker) })
  }
  return fields
}

/** A record of `fields` that writes its own JSON: the page's names, nothing for what is left null. */
function recordCode(R: string, fields: Field[], doc: string, implement: string, indent: string, constants: [string, string][] = [], inner: string[] = []): string {
  const params = fields.map((f) => `${f.type} ${f.java}`).join(", ")
  const puts = fields
    .map((f) => (/^(double|boolean|long|int)$/.test(f.type) ? `${indent}        m.put("${f.name}", ${f.java});` : `${indent}        if (${f.java} != null) m.put("${f.name}", ${f.java});`))
    .join("\n")
  const required = fields.filter((f) => f.required)
  const short =
    required.length < fields.length && required.length > 0
      ? `\n${indent}    /** Only what it needs; the rest left out (with... adds them). */\n${indent}    public ${R}(${required.map((f) => `${f.type} ${f.java}`).join(", ")}) {\n${indent}        this(${fields.map((f) => (f.required ? f.java : "null")).join(", ")});\n${indent}    }\n`
      : ""
  // the optional parts, one at a time: new Conversation("ana", "Ana").withUnread(1.0).withPinned(true)
  const withers = fields
    .filter((f) => !f.required)
    .map((f) => {
      const W = `with${up(f.java)}`
      const args = fields.map((g) => (g === f ? f.java : g.java)).join(", ")
      return `${indent}    public ${R} ${W}(${f.type} ${f.java}) { return new ${R}(${args}); }`
    })
    .join("\n")
  const params_ = fields.filter((f) => f.doc).map((f) => `@param ${f.java} ${esc(f.doc).split("\n")[0]}`)
  const docText = [doc ? esc(doc) : "", ...params_].filter(Boolean).join("\n")
  const header = docText ? javadoc("", indent, docText) : ""
  return (
    `${header}${indent}public record ${R}(${params}) implements ${implement} {\n` +
    short +
    (withers ? `\n${withers}\n` : "") +
    `\n${indent}    @Override public Object json() {\n${indent}        java.util.Map<String, Object> m = new java.util.LinkedHashMap<>();\n` +
    constants.map(([k, v]) => `${indent}        m.put("${k}", "${v}");\n`).join("") +
    `${puts}\n${indent}        return m;\n${indent}    }\n` +
    // its own parts with no name in TypeScript (a conversation's last message), inside it
    (inner.length ? `\n${inner.map((d) => d.replace(/^/gm, indent ? "" : "")).join("\n\n")}\n` : "") +
    `${indent}}`
  )
}

/** A shared type's own context: its unnamed parts go inside it. */
function innerContext(ctx: TypeContext, owner: string): TypeContext {
  return { checker: ctx.checker, owner, decls: [], byType: new Map(), names: new Set() }
}

function recordOf(t: ts.Type, ctx: TypeContext, hint: string, declared?: string): string {
  const doc = t.aliasSymbol ? docOf(t.aliasSymbol, ctx.checker) : t.symbol ? docOf(t.symbol, ctx.checker) : ""
  const share = declaredName(t, declared)
  if (share) {
    const known = SHARED.byType.get(t)
    if (known) return known
    const R = sharedName(share)
    SHARED.byType.set(t, R) // before its fields: a record may hold itself (a folder's folders)
    SHARED.files.set(R, "") // its name is taken while its fields are read
    const inner = innerContext(ctx, R)
    const fields = fieldsOf(t, inner)
    SHARED.files.set(R, sharedFile(recordCode(R, fields, doc, "JsonValue", "", constantsOf(t, inner), inner.decls), share))
    return R
  }
  const R = typeName(t, ctx, hint)
  ctx.byType.set(t, R)
  const fields = fieldsOf(t, ctx)
  ctx.decls.push(recordCode(R, fields, doc, "JsonValue", "    ", constantsOf(t, ctx)))
  return R
}

/** A union of objects told apart by one field with a different word in each: a sealed interface of records. */
function sealedOf(members: ts.Type[], type: ts.Type, ctx: TypeContext, hint: string, declared?: string): string | undefined {
  const { checker } = ctx
  const first = checker.getPropertiesOfType(members[0]).map((p) => p.name)
  const tag = first.find((name) =>
    members.every((m) => {
      const p = checker.getPropertyOfType(m, name)
      return p && checker.getTypeOfSymbol(p).isStringLiteral()
    })
  )
  if (!tag) return undefined
  const values = members.map((m) => (checker.getTypeOfSymbol(checker.getPropertyOfType(m, tag)!) as ts.StringLiteralType).value)
  if (new Set(values).size !== values.length) return undefined
  const doc = type.aliasSymbol ? docOf(type.aliasSymbol, checker) : ""
  const share = declaredName(type, declared)
  if (share && SHARED.byType.get(type)) return SHARED.byType.get(type)
  const S = share ? sharedName(share) : typeName(type, ctx, hint)
  if (share) {
    SHARED.byType.set(type, S)
    SHARED.files.set(S, "")
  } else ctx.byType.set(type, S)
  // shared: at the top of its own file; nested: inside the component
  const indent = share ? "" : "    "
  const inner = share ? innerContext(ctx, S) : ctx
  const records = members.map((m, i) => {
    const R = up(javaName(values[i]))
    return recordCode(R, fieldsOf(m, inner, tag), "", S, `${indent}    `, constantsOf(m, inner))
  })
  const code =
    javadoc(doc, indent, `One of these, told apart by {@code ${tag}}.`) +
    `${indent}public sealed interface ${S} extends JsonValue {\n${records.join("\n\n")}` +
    (share && inner.decls.length ? `\n\n${inner.decls.join("\n\n")}` : "") +
    `\n${indent}}`
  if (share) SHARED.files.set(S, sharedFile(code, share))
  else ctx.decls.push(code)
  return S
}

function javaName(prop: string): string {
  let name = prop.replace(/[-_ ]+([a-zA-Z0-9])/g, (_, c: string) => c.toUpperCase()).replace(/[^A-Za-z0-9]/g, "")
  if (/^[0-9]/.test(name)) name = `p${name}`
  if (JAVA_KEYWORDS.has(name)) name = `${name}Value`
  return name
}

function readModel(entry: Entry, prog: ts.Program): Model {
  const checker = prog.getTypeChecker()
  const file = prog.getSourceFile(path.join(UI, entry.from))
  if (!file) fail(`${entry.from}: no such file`)
  const moduleSymbol = checker.getSymbolAtLocation(file)
  if (!moduleSymbol) fail(`${entry.from}: not a module`)
  let symbol = checker.getExportsOfModule(moduleSymbol).find((s) => s.name === entry.component)
  if (!symbol) fail(`${entry.from} does not export ${entry.component}`)
  if (symbol.flags & ts.SymbolFlags.Alias) symbol = checker.getAliasedSymbol(symbol)
  const componentType = checker.getTypeOfSymbol(symbol)
  const signature = componentType.getCallSignatures()[0]
  if (!signature) fail(`${entry.component} is not a component (it cannot be called with props)`)
  const propsParam = signature.getParameters()[0]
  if (!propsParam) fail(`${entry.component} takes no props`)
  const propsType = checker.getTypeOfSymbol(propsParam)

  const skip = new Set(entry.skip ?? [])
  const props: Prop[] = []
  const left: string[] = []
  const ctx: TypeContext = { checker, owner: entry.java, decls: [], byType: new Map(), names: new Set() }
  const symbols = new Map<string, ts.Symbol>()
  let children = false
  let style = false
  for (const p of checker.getPropertiesOfType(propsType)) {
    if (p.name === "style") style = true
    if (SKIPPED_ALWAYS.has(p.name) || skip.has(p.name)) continue
    if (p.name === "children") {
      if (isOwn(p)) children = true
      continue
    }
    // Only the component's own props: not the hundreds a <div> takes (aria-label stays when declared here).
    if (!isOwn(p)) continue
    const required = !(p.flags & ts.SymbolFlags.Optional)
    const kind = kindOf(checker.getTypeOfSymbol(p), checker)
    if (!kind) {
      left.push(`${p.name}: ${checker.typeToString(checker.getTypeOfSymbol(p))}`)
      if (required) fail(`${entry.component}.${p.name} is required but has no Java form; add it to "skip" only if it has a default`)
      continue
    }
    props.push({ name: p.name, java: javaName(p.name), kind, required, doc: docOf(p, checker) })
    symbols.set(p.name, p)
  }
  // the prop enums' names first (Chart.Kind): a data type never takes one
  for (const p of props) if (p.kind.k === "enum") ctx.names.add(up(p.java))
  // each data prop's own Java type, named after TypeScript's type (or the prop): records, lists, enums
  for (const p of props) {
    if (p.kind.k !== "data") continue
    const s = symbols.get(p.name)!
    p.jt = javaTypeOf(checker.getTypeOfSymbol(s), ctx, hintOf(s), true, declaredOf(s))
  }
  return { entry, doc: docOf(symbol, checker), props, children, style, left, types: ctx.decls }
}

// ---------------------------------------------------------------- Java

const up = (s: string) => s[0].toUpperCase() + s.slice(1)
const constant = (v: string) => {
  const c = v.replace(/([a-z0-9])([A-Z])/g, "$1_$2").replace(/[^A-Za-z0-9]+/g, "_").replace(/^_|_$/g, "").toUpperCase()
  return /^[0-9]/.test(c) || c === "" ? `V_${c}` : c
}

/** The component's own words, safe in a Javadoc comment. */
const esc = (text: string) => text.replace(/\*\//g, "*&#47;").replace(/@/g, "{@literal @}")

/** A Javadoc comment of `text` (the component's words) and `extra` (java-gen's own markup, as is). */
function javadoc(text: string, indent: string, extra = ""): string {
  const all = [esc(text), extra].filter(Boolean).join("\n")
  if (!all) return ""
  const safe = all.split("\n").map((l) => l.trimEnd())
  if (safe.length === 1 && safe[0].length < 100) return `${indent}/** ${safe[0]} */\n`
  return `${indent}/**\n${safe.map((l) => `${indent} * ${l}`.trimEnd()).join("\n")}\n${indent} */\n`
}

function javaParam(prop: Prop): string {
  switch (prop.kind.k) {
    case "string":
    case "node":
      return "String"
    case "number":
      return "double"
    case "boolean":
      return "boolean"
    case "enum":
      return up(prop.java)
    case "data":
      return asParam(prop.jt ?? "Object")
    default:
      return "Object"
  }
}

function javaValue(prop: Prop, name: string): string {
  return prop.kind.k === "enum" ? `${name}.key` : name
}

function javaClass(model: Model): string {
  const { entry } = model
  const C = entry.java
  const lines: string[] = []
  const enums: string[] = []
  const required = model.props.filter((p) => p.required && p.kind.k !== "callback")
  const params = required.map((p) => `${javaParam(p)} ${p.java}`).join(", ")
  const usesConsumer = model.props.some((p) => p.kind.k === "callback" && p.kind.arg !== "none")
  const usesList = model.props.some((p) => p.kind.k === "callback" && p.kind.arg === "args")

  for (const p of model.props) {
    const doc = javadoc(p.doc, "    ")
    const inherited = INHERITED.has(p.java)
    switch (p.kind.k) {
      case "string":
        if (inherited) break
        lines.push(`${doc}    public ${C} ${p.java}(String ${p.java}) { return prop("${p.name}", ${p.java}); }`)
        break
      case "number":
        if (inherited) break // Component's own (width, height...) sets the same prop
        lines.push(`${doc}    public ${C} ${p.java}(double ${p.java}) { return prop("${p.name}", ${p.java}); }`)
        break
      case "boolean":
        if (inherited) break
        lines.push(`${doc}    public ${C} ${p.java}(boolean ${p.java}) { return prop("${p.name}", ${p.java}); }`)
        if (!p.required) lines.push(`    public ${C} ${p.java}() { return ${p.java}(true); }`)
        break
      case "multi":
        if (inherited) break
        for (const k of p.kind.kinds) {
          const jt = k === "string" ? "String" : k === "number" ? "double" : "boolean"
          lines.push(`${doc}    public ${C} ${p.java}(${jt} ${p.java}) { return prop("${p.name}", ${p.java}); }`)
        }
        break
      case "enum": {
        if (inherited) break
        const E = up(p.java)
        enums.push(
          `    /** {@link #${p.java}(${E})}'s choices. */\n` +
            `    public enum ${E} {\n` +
            p.kind.values.map((v) => `        ${constant(v)}("${v}")`).join(",\n") +
            `;\n\n        final String key;\n\n        ${E}(String key) { this.key = key; }\n    }`
        )
        lines.push(`${doc}    public ${C} ${p.java}(${E} ${p.java}) { return prop("${p.name}", ${p.java} == null ? null : ${p.java}.key); }`)
        break
      }
      case "node":
        if (inherited) break
        lines.push(`${doc}    public ${C} ${p.java}(String ${p.java}) { return prop("${p.name}", ${p.java}); }`)
        lines.push(`    /** In place of the text: any component. */\n    public ${C} ${p.java}(Component<?> ${p.java}) { return add(slot(${p.java}, "${p.name}")); }`)
        break
      case "data": {
        if (inherited) break
        const jt = asParam(p.jt ?? "Object")
        const loose = /(^|<)Object(>|$)|<\?>/.test(jt)
        lines.push(
          javadoc(p.doc, "    ", loose ? `Any record or map of yours for each: {@code ${p.kind.ts.replace(/ \| undefined$/, "").replace(/[{}@<>]/g, (b) => `&#${b.charCodeAt(0)};`)}}` : "") +
            `    public ${C} ${p.java}(${jt} ${p.java}) { return prop("${p.name}", ${p.java}); }`
        )
        break
      }
      case "callback": {
        const arg = p.kind.arg
        if (arg === "none") lines.push(`${doc}    public ${C} ${p.java}(Runnable action) { return on("${p.name}", v -> action.run()); }`)
        else {
          const [jt, conv] =
            arg === "string" ? ["String", "Keys.text(v)"]
            : arg === "number" ? ["Double", "Keys.number(v)"]
            : arg === "boolean" ? ["Boolean", "Keys.flag(v)"]
            : arg === "args" ? ["List<Object>", "v instanceof List<?> l ? java.util.Collections.unmodifiableList(new java.util.ArrayList<Object>(l)) : List.of()"]
            : ["Object", "v"]
          lines.push(`${doc}    public ${C} ${p.java}(Consumer<${jt}> action) { return on("${p.name}", v -> action.accept(${conv})); }`)
          lines.push(`    public ${C} ${p.java}(Runnable action) { return on("${p.name}", v -> action.run()); }`)
        }
        break
      }
    }
  }
  if (model.children) lines.push(`    /** What it holds. */\n    public ${C} with(Component<?>... children) { return add(children); }`)

  const ctorBody = [`        super("${entry.type}");`]
  for (const p of required) ctorBody.push(`        prop("${p.name}", ${javaValue(p, p.java)});`)

  const imports = ["import io.joshuasalcedo.webview4j.ui.Component;"]
  if (model.types.length) imports.unshift("import io.joshuasalcedo.webview4j.JsonValue;")
  if (usesList) imports.push("import java.util.List;")
  if (usesConsumer) imports.push("import java.util.function.Consumer;")
  // the records and enums its data is made of, before the rest
  if (model.types.length) enums.push(...model.types)

  const notes = model.left.length
    ? `\n *\n * <p>Not in Java (no JSON form): ${model.left.map((l) => `{@code ${l.split(":")[0]}}`).join(", ")}.`
    : ""
  const classDoc = (model.doc || `{@code ${entry.component}} from {@code @webview4j/ui}.`).replace(/\*\//g, "*&#47;")
  return `${HEADER} from ${entry.from} (${entry.component}): do not edit.
// Change the component's props, then run \`bun run java-gen\` in core/src/main/ui.
package io.joshuasalcedo.webview4j.ui.components;

${imports.join("\n")}

/**
${classDoc.split("\n").map((l) => ` * ${l}`.trimEnd()).join("\n")}${notes}
 */
public final class ${C} extends Component<${C}> {
${enums.length ? "\n" + enums.join("\n\n") + "\n" : ""}
    public ${C}(${params}) {
${ctorBody.join("\n")}
    }
${lines.length ? "\n" + lines.join("\n") + "\n" : ""}}
`
}

// ---------------------------------------------------------------- the renderer's side

function tsValue(p: Prop): string {
  const v = `p[${JSON.stringify(p.name)}]`
  switch (p.kind.k) {
    case "string":
      return p.required ? `str(${v}) ?? ""` : `str(${v})`
    case "number":
      return p.required ? `num(${v}) ?? 0` : `num(${v})`
    case "boolean":
      return p.required ? `${v} === true` : `flag(${v})`
    case "multi": {
      const test = p.kind.kinds.map((k) => `typeof ${v} === "${k}"`).join(" || ")
      return `(${test}) ? (${v} as ${p.kind.kinds.join(" | ")}) : undefined`
    }
    case "enum":
      return `oneOf(${v}, ${JSON.stringify(p.kind.values)} as const)${p.required ? `!` : ""}`
    case "node":
      return p.required ? `place(node, ${JSON.stringify(p.name)}, child) ?? ""` : `place(node, ${JSON.stringify(p.name)}, child)`
    case "data":
      return `${v} as never`
    case "callback": {
      const has = `typeof ${v} === "string"`
      // async: fits a prop that wants a promise (onUnlock) as well as one that wants nothing.
      const call =
        p.kind.arg === "none" ? `async () => send(${v})`
        : p.kind.arg === "args" ? `async (...args: unknown[]) => send(${v}, args.map((a, i) => (${JSON.stringify(p.kind.mask)}[i] ? a : null)))`
        : p.kind.arg === "pick" ? `async (value: unknown) => send(${v}, pick(value, ${JSON.stringify(p.kind.keys)}))`
        : `async (value: unknown) => send(${v}, value)`
      return p.required ? `${has} ? ${call} : () => {}` : `${has} ? ${call} : undefined`
    }
  }
}

function tsCase(m: Model): string {
  const attrs = m.props.map((p) => `          ${JSON.stringify(p.name).slice(1, -1).includes("-") ? `{...{ ${JSON.stringify(p.name)}: ${tsValue(p)} }}` : `${p.name}={${tsValue(p)}}`}`)
  if (m.style) attrs.push(`          style={style}`)
  const open = `        <${m.entry.component}\n${attrs.join("\n")}\n        `
  const element = m.children ? `${open}>\n          {rest(node, child)}\n        </${m.entry.component}>` : `${open}/>`
  // A lazy one loads the first time it is shown: nothing while it does.
  const body = m.entry.lazy ? `        <React.Suspense fallback={null}>\n${element.replace(/^/gm, "  ")}\n        </React.Suspense>` : element
  return `    case ${JSON.stringify(m.entry.type)}:
      return (
${body}
      )`
}

function specOf(m: Model): string {
  return "./" + path.relative(path.join(UI, "src"), path.join(UI, m.entry.from)).replace(/\\/g, "/").replace(/\.tsx?$/, "")
}

function generatedTsx(models: Model[]): string {
  const imports = new Map<string, string[]>()
  for (const m of models) {
    if (m.entry.lazy) continue
    imports.set(specOf(m), [...(imports.get(specOf(m)) ?? []), m.entry.component])
  }
  const importLines = [...imports].sort(([a], [b]) => a.localeCompare(b)).map(([spec, names]) => `import { ${[...new Set(names)].sort().join(", ")} } from "${spec}"`)
  for (const m of models.filter((m) => m.entry.lazy)) {
    importLines.push(
      `/** ${m.entry.component} loads the first time a screen shows one (java-gen.json: lazy). */\n` +
        `const ${m.entry.component} = React.lazy(() => import("${specOf(m)}").then((m) => ({ default: m.${m.entry.component} })))`
    )
  }
  const uses = (s: string) => models.some((m) => m.props.some((p) => tsValue(p).includes(s)))
  const helpers = [
    uses("str(") && `const str = (v: unknown) => (typeof v === "string" ? v : undefined)`,
    uses("num(") && `const num = (v: unknown) => (typeof v === "number" ? v : undefined)`,
    uses("flag(") && `const flag = (v: unknown) => (typeof v === "boolean" ? v : undefined)`,
    uses("oneOf(") &&
      `function oneOf<const T extends readonly string[]>(v: unknown, values: T): T[number] | undefined {\n  return typeof v === "string" && (values as readonly string[]).includes(v) ? (v as T[number]) : undefined\n}`,
    uses("place(") &&
      `/** A named place: the component Java put there, else its text. */\nfunction place(node: JavaNode, name: string, child: Child): React.ReactNode {\n  const i = (node.c ?? []).findIndex((c) => c.p.slot === name)\n  if (i >= 0) return child(node.c![i], i)\n  return typeof node.p[name] === "string" ? (node.p[name] as string) : undefined\n}`,
    uses("pick(") &&
      `/** Only the parts of an event Java can get (its text, not its File objects). */\nfunction pick(value: unknown, keys: string[]): Record<string, unknown> {\n  const from = (value ?? {}) as Record<string, unknown>\n  return Object.fromEntries(keys.filter((k) => k in from).map((k) => [k, from[k]]))\n}`,
    models.some((m) => m.children) &&
      `/** The children that fill no named place. */\nfunction rest(node: JavaNode, child: Child): React.ReactNode {\n  return (node.c ?? []).map((c, i) => (typeof c.p.slot === "string" ? null : child(c, i)))\n}`,
  ].filter(Boolean)
  const usesSend = models.some((m) => m.props.some((p) => p.kind.k === "callback"))
  const usesChild = models.some((m) => m.children || m.props.some((p) => p.kind.k === "node"))
  const usesStyle = models.some((m) => m.style)
  const params = [usesSend && "send", usesStyle && "style", usesChild && "child"].filter(Boolean).join(", ")

  return `${HEADER} from java-gen.json: do not edit. Run \`bun run java-gen\`.
// Components drawn for Java screens that java-ui.tsx has no case of its own for: it asks here last.
import * as React from "react"

${importLines.join("\n")}

type JavaNode = { t: string; p: Record<string, unknown>; c?: JavaNode[]; k?: string }
type Child = (node: JavaNode, index: number) => React.ReactNode

/** What the renderer gives: how to answer Java, the node's sizing, and how to draw a child. */
export type Generated = {
  send: (handler: unknown, value?: unknown) => void
  style: React.CSSProperties
  child: Child
}

${helpers.join("\n\n")}

/** The component for \`node\`, or undefined when its type is not a generated one. */
export function renderGenerated(node: JavaNode, ${params ? `{ ${params} }` : "_"}: Generated): React.ReactNode | undefined {
  const p = node.p
  switch (node.t) {
${models.map(tsCase).join("\n")}
    default:
      return undefined
  }
}

/** The node types drawn here. */
export const generatedTypes: readonly string[] = ${JSON.stringify(models.map((m) => m.entry.type))}
`
}

// ---------------------------------------------------------------- writing

function main() {
  const check = process.argv.includes("--check")
  const entries = readManifest()
  const taken = handWrittenTypes()
  for (const e of entries) if (taken.has(e.type)) fail(`"${e.type}" already has a case in java-ui.tsx: give ${e.component} another type`)

  // the hand-written classes beside the generated ones: reused when they fit (PillColor), their names never taken
  for (const f of fs.readdirSync(JAVA_DIR).filter((f) => f.endsWith(".java"))) {
    const text = fs.readFileSync(path.join(JAVA_DIR, f), "utf8")
    if (!text.startsWith(HEADER)) SHARED.handWritten.set(f.slice(0, -5), text)
  }
  for (const name of SHARED.handWritten.keys()) SHARED.reserved.add(name)
  for (const e of entries) SHARED.reserved.add(e.java)

  const prog = program()
  const models = entries.map((e) => readModel(e, prog))

  const outputs = new Map<string, string>()
  for (const m of models) outputs.set(path.join(JAVA_DIR, `${m.entry.java}.java`), javaClass(m))
  // the types they share, one file each
  for (const [name, text] of SHARED.files) {
    if (!text) fail(`${name}: its type was never finished (a loop java-gen cannot follow)`)
    outputs.set(path.join(JAVA_DIR, `${name}.java`), text)
  }
  outputs.set(GENERATED_TSX, generatedTsx(models))

  // Generated Java files no longer in the manifest: removed with it.
  const stale = fs.readdirSync(JAVA_DIR)
    .map((f) => path.join(JAVA_DIR, f))
    .filter((f) => f.endsWith(".java") && !outputs.has(f) && fs.readFileSync(f, "utf8").startsWith(HEADER))

  for (const [file] of outputs) {
    if (fs.existsSync(file) && !fs.readFileSync(file, "utf8").startsWith(HEADER))
      fail(`${path.relative(UI, file)} is hand-written: java-gen does not overwrite it (rename the entry's "java")`)
  }

  const differ = [...outputs].filter(([file, text]) => !fs.existsSync(file) || fs.readFileSync(file, "utf8") !== text)
  if (check) {
    if (differ.length || stale.length) {
      for (const [f] of differ) console.error(`java-gen: out of date: ${path.relative(UI, f)}`)
      for (const f of stale) console.error(`java-gen: no longer generated: ${path.relative(UI, f)}`)
      fail("run `bun run java-gen` in core/src/main/ui")
    }
    console.log(`java-gen: ${models.length} components up to date`)
    return
  }
  for (const [file, text] of differ) fs.writeFileSync(file, text)
  for (const f of stale) fs.rmSync(f)
  for (const m of models) {
    const made = m.props.map((p) => p.name).join(", ")
    console.log(`${m.entry.java} (${m.entry.type}): ${made || "no props"}${m.children ? ", children" : ""}`)
    if (m.left.length) console.log(`  left out: ${m.left.join("; ")}`)
  }
  console.log(`java-gen: wrote ${differ.length}, removed ${stale.length}, ${outputs.size - differ.length} unchanged`)
}

main()
