// css-gen: the kit's style files as typed Java (io.joshuasalcedo.webview4j.ui.styles), read from the CSS itself.
//
//   bun run css-gen          writes them
//   bun run css-gen:check    fails if what is written is not what the CSS gives (the build runs it)
//
// Each src/styles/<name>.css becomes <Name>Style, an enum implementing Style: one constant per class the file
// styles (.nt-filetree-row is FileStyle.FILETREE_ROW), given with component.style(FileStyle.FILETREE_ROW); and a
// static method per custom property it declares (--nt-indent is FileStyle.indent(20)), a Style setting it. The CSS
// files are read, never written.

import * as fs from "node:fs"
import * as path from "node:path"
import * as process from "node:process"

const UI = path.resolve(import.meta.dirname, "..")
const STYLES = path.join(UI, "src/styles")
const OUT = path.resolve(UI, "../java/io/joshuasalcedo/webview4j/ui/styles")
const HEADER = "// Generated by core/src/main/ui/scripts/css-gen.ts from src/styles/"
/** Words that are not Java names on their own. */
const RESERVED = new Set(["abstract", "assert", "boolean", "break", "byte", "case", "catch", "char", "class", "const", "continue",
  "default", "do", "double", "else", "enum", "extends", "final", "finally", "float", "for", "goto", "if", "implements", "import",
  "instanceof", "int", "interface", "long", "native", "new", "package", "private", "protected", "public", "return", "short",
  "static", "strictfp", "super", "switch", "synchronized", "this", "throw", "throws", "transient", "try", "void", "volatile",
  "while", "var", "record", "yield", "sealed", "permits", "values", "valueOf", "classNames", "declarations", "file"])

type Clazz = { name: string; selector: string; doc: string }
type Variable = { name: string; value: string; selector: string; doc: string }
type Sheet = { file: string; java: string; doc: string; classes: Clazz[]; variables: Variable[] }

const pascal = (s: string) => s.split(/[^A-Za-z0-9]+/).filter(Boolean).map((w) => w[0].toUpperCase() + w.slice(1)).join("")
const camel = (s: string) => {
  const p = pascal(s)
  const c = p[0].toLowerCase() + p.slice(1)
  return RESERVED.has(c) || /^[0-9]/.test(c) ? c + "Value" : c
}
const constant = (s: string) => {
  const c = s.replace(/^nt-/, "").replace(/[^A-Za-z0-9]+/g, "_").toUpperCase()
  return /^[0-9]/.test(c) ? "V_" + c : c
}
/** Safe in a Javadoc comment. */
const esc = (s: string) => s.replace(/\*\//g, "*&#47;").replace(/@/g, "{@literal @}").replace(/</g, "&lt;").replace(/>/g, "&gt;")
const clean = (comment: string) => comment.replace(/^\/\*+|\*+\/$/g, "").split("\n").map((l) => l.replace(/^\s*\*\s?/, "").trim())
  .filter((l) => l && !/^-+$/.test(l) && !/^-{3}/.test(l) || /^-{3}\s*\S/.test(l)).map((l) => l.replace(/^-+\s*|\s*-+$/g, "")).join(" ").trim()

function read(file: string): Sheet {
  const css = fs.readFileSync(path.join(STYLES, file), "utf8")
  const first = css.match(/^\s*(\/\*[\s\S]*?\*\/)/)
  const doc = first ? clean(first[1]) : ""
  const classes = new Map<string, Clazz>()
  const variables = new Map<string, Variable>()
  // Rules with the comment just before them: "/* a */ .x { … }"; @media and @supports blocks are read through.
  const rule = /(\/\*[\s\S]*?\*\/\s*)?([^{}@/][^{}]*?)\{([^{}]*)\}/g
  for (const m of css.matchAll(rule)) {
    const comment = m[1] ? clean(m[1]) : ""
    const selector = m[2].replace(/\/\*[\s\S]*?\*\//g, "").replace(/\s+/g, " ").trim()
    const body = m[3].replace(/\/\*[\s\S]*?\*\//g, "")
    for (const c of selector.matchAll(/\.(nt-[A-Za-z0-9_-]+)/g)) {
      if (!classes.has(c[1])) classes.set(c[1], { name: c[1], selector, doc: comment })
    }
    for (const d of body.matchAll(/(--nt-[A-Za-z0-9-]+)\s*:\s*([^;]+);?/g)) {
      if (!variables.has(d[1])) variables.set(d[1], { name: d[1], value: d[2].trim().replace(/\s+/g, " "), selector, doc: comment })
    }
  }
  return { file, java: pascal(file.replace(/\.css$/, "")) + "Style", doc, classes: [...classes.values()], variables: [...variables.values()] }
}

/** A custom property whose default is a length in px (or a bare number): set from a double too. */
const isPx = (v: string) => /^-?[0-9.]+px$/.test(v)
const isNumber = (v: string) => /^-?[0-9.]+$/.test(v)

function java(sheet: Sheet): string {
  const lines: string[] = []
  lines.push(`${HEADER}${sheet.file}: do not edit; run \`bun run css-gen\` in core/src/main/ui.`)
  lines.push(`package io.joshuasalcedo.webview4j.ui.styles;`, ``)
  lines.push(`import io.joshuasalcedo.webview4j.ui.InlineStyle;`, `import io.joshuasalcedo.webview4j.ui.Style;`, `import java.util.List;`, ``)
  lines.push(`/**`, ` * ${esc(sheet.doc || sheet.file)}`, ` * <p>The classes of {@code ${sheet.file}}: {@code component.style(${sheet.java}.${sheet.classes[0] ? constant(sheet.classes[0].name) : "…"})}.`)
  if (sheet.variables.length) lines.push(` * Its custom properties: {@code ${sheet.java}.${camel(sheet.variables[0].name.replace(/^--nt-/, ""))}(…)}, a {@link Style} setting one.`)
  lines.push(` */`, `public enum ${sheet.java} implements Style {`)
  sheet.classes.forEach((c, i) => {
    const doc = [`{@code .${c.name}}`, c.doc ? esc(c.doc) : "", `(first in {@code ${esc(c.selector)}})`].filter(Boolean).join(": ")
    lines.push(`    /** ${doc} */`)
    lines.push(`    ${constant(c.name)}("${c.name}")${i === sheet.classes.length - 1 ? ";" : ","}`)
  })
  if (!sheet.classes.length) lines.push(`    ;`)
  lines.push(``, `    /** The style file these come from, as the page has it. */`, `    public static final String FILE = "styles/${sheet.file}";`, ``)
  lines.push(`    private final String className;`, ``, `    ${sheet.java}(String className) {`, `        this.className = className;`, `    }`, ``)
  lines.push(`    /** The CSS class, as the page has it ({@code ${sheet.classes[0]?.name ?? "nt-…"}}). */`, `    public String className() {`, `        return className;`, `    }`, ``)
  lines.push(`    @Override`, `    public List<String> classNames() {`, `        return List.of(className);`, `    }`)
  const seen = new Set<string>()
  for (const v of sheet.variables) {
    let m = camel(v.name.replace(/^--nt-/, ""))
    while (seen.has(m)) m += "_"
    seen.add(m)
    const where = `(${esc(v.value)} on {@code ${esc(v.selector)}})`
    const doc = [`{@code ${v.name}}`, v.doc ? esc(v.doc) : "", where].filter(Boolean).join(": ")
    lines.push(``, `    /** ${doc} */`)
    lines.push(`    public static InlineStyle ${m}(String value) {`, `        return Style.of().set("${v.name}", value);`, `    }`)
    if (isPx(v.value)) {
      lines.push(``, `    /** {@code ${v.name}} in CSS pixels. */`, `    public static InlineStyle ${m}(double px) {`, `        return Style.of().set("${v.name}", InlineStyle.number(px) + "px");`, `    }`)
    } else if (isNumber(v.value)) {
      lines.push(``, `    /** {@code ${v.name}} as a number. */`, `    public static InlineStyle ${m}(double value) {`, `        return Style.of().set("${v.name}", InlineStyle.number(value));`, `    }`)
    }
  }
  lines.push(`}`, ``)
  return lines.join("\n")
}

function main() {
  const check = process.argv.includes("--check")
  const files = fs.readdirSync(STYLES).filter((f) => f.endsWith(".css")).sort()
  const want = new Map<string, string>()
  for (const f of files) {
    const sheet = read(f)
    want.set(path.join(OUT, sheet.java + ".java"), java(sheet))
  }
  const have = fs.existsSync(OUT) ? fs.readdirSync(OUT).filter((f) => f.endsWith("Style.java")).map((f) => path.join(OUT, f)) : []
  const stale = have.filter((f) => !want.has(f) && fs.readFileSync(f, "utf8").startsWith(HEADER))
  const differ = [...want].filter(([f, t]) => !fs.existsSync(f) || fs.readFileSync(f, "utf8") !== t)
  if (check) {
    if (differ.length || stale.length) {
      console.error(`css-gen: out of date (${[...differ.map(([f]) => f), ...stale].map((f) => path.basename(f)).join(", ")}): run \`bun run css-gen\` in core/src/main/ui`)
      process.exit(1)
    }
    console.log(`css-gen: ${want.size} style files up to date`)
    return
  }
  fs.mkdirSync(OUT, { recursive: true })
  for (const [f, t] of differ) fs.writeFileSync(f, t)
  for (const f of stale) fs.rmSync(f)
  console.log(`css-gen: ${want.size} style files, ${differ.length} written, ${stale.length} removed`)
}

main()
