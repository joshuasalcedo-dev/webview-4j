// html-gen: the HTML elements as typed Java (io.joshuasalcedo.webview4j.ui.Html), read from React's own types.
//
//   bun run html-gen          writes them
//   bun run html-gen:check    fails if what is written is not what React's types give (the build runs it)
//
// Each element React types (React.JSX.IntrinsicElements) becomes Html.<Element>, with only its own attributes
// (InputHTMLAttributes' accept, checked, type... not HTMLAttributes', which every Component has as HTML's global
// attributes): a string union is an enum (and, where any text goes too, a String overload); a URL attribute is
// checked. Left out: deprecated and non-standard elements (MDN), the page's own frame, and whatever runs code or
// loads another site. Also written: src/html-tags.generated.ts, the tags the renderer draws.

import * as fs from "node:fs"
import * as path from "node:path"
import * as process from "node:process"
import ts from "typescript"

const UI = path.resolve(import.meta.dirname, "..")
const HTML_JAVA = path.resolve(UI, "../java/io/joshuasalcedo/webview4j/ui/Html.java")
const TAGS_TS = path.join(UI, "src/html-tags.generated.ts")
const HEADER = "// Generated by core/src/main/ui/scripts/html-gen.ts"

/** MDN's obsolete and deprecated elements (Web/HTML/Reference/Elements, read 2026-11-25), and React's non-standard ones. */
const DEPRECATED = new Set(["acronym", "big", "center", "content", "dir", "fencedframe", "font", "frame", "frameset", "image", "marquee",
  "menuitem", "nobr", "noembed", "noframes", "param", "plaintext", "rb", "rtc", "shadow", "strike", "tt", "xmp", "keygen", "noindex", "webview"])
/** Left out on purpose: the page's own frame; what runs code or loads another site (the embed component is for sites); style (styleSheet). */
const LEFT_OUT: Record<string, string> = {
  html: "the page's own", head: "the page's own", body: "the page's own", title: "the window's title is WindowOptions.title",
  base: "would move every link", meta: "the page's own", link: "loads outside files", style: "Ui.styleSheet",
  script: "runs code", noscript: "for pages without scripts", iframe: "loads another site (the embed component)",
  object: "loads a plugin or another site", embed: "loads a plugin or another site",
}
/** HTML's void elements: no children, no closing tag. */
const VOID = new Set(["area", "br", "col", "hr", "img", "input", "source", "track", "wbr"])
/** The attribute interfaces whose props are not an element's own (global attributes, React's own, ARIA, events). */
const NOT_OWN = new Set(["HTMLAttributes", "AllHTMLAttributes", "DOMAttributes", "AriaAttributes", "ClassAttributes", "Attributes", "RefAttributes"])
/** Attributes holding a URL: checked in Java (HtmlElement.url) and again by the renderer. */
const URLS = new Set(["href", "src", "action", "formAction", "poster", "cite", "data", "ping", "manifest", "codeBase", "itemType"])
/** React's names that never become Java methods here. */
const SKIP = new Set(["children", "dangerouslySetInnerHTML", "suppressContentEditableWarning", "suppressHydrationWarning",
  "key", "ref", "style", "className", "defaultChecked", "defaultValue"])
/** HtmlElement's and Component's own methods: an attribute of the same name is not given one (its own is used). */
const TAKEN = new Set(["with", "text", "onClick", "onDoubleClick", "onPointerEnter", "onPointerLeave", "onFocus", "onBlur", "onKeyDown",
  "onInput", "onChange", "onSubmit", "onToggle", "attribute", "url", "key", "grow", "width", "height", "minWidth", "maxWidth", "minHeight",
  "maxHeight", "prop", "on", "add", "get", "children", "slot", "self", "id", "className", "attr", "dataAttribute", "ariaAttribute",
  "hidden", "tabIndex", "style", "css", "accessKey", "anchor", "autoCapitalize", "autoCorrect", "autofocus", "contentEditable", "dir",
  "draggable", "enterKeyHint", "exportParts", "inert", "inputMode", "lang", "nonce", "part", "popover", "role", "slotName", "spellCheck",
  "htmlTitle", "translate", "itemId", "itemProp", "itemRef", "itemScope", "itemType", "title", "hoverStyle", "focusStyle",
  "pressedStyle", "onHover", "browserLook"])
const JAVA_KEYWORDS = new Set(["default", "class", "for", "new", "public", "private", "static", "final", "switch", "case", "package",
  "import", "interface", "enum", "boolean", "int", "double", "long", "char", "byte", "short", "float", "void", "this", "super",
  "return", "throw", "throws", "try", "catch", "finally", "if", "else", "while", "do", "break", "continue", "abstract", "native",
  "synchronized", "transient", "volatile", "assert", "const", "goto", "instanceof", "extends", "implements", "protected", "strictfp"])

function fail(message: string): never {
  console.error(`html-gen: ${message}`)
  process.exit(1)
}

const up = (s: string) => s[0].toUpperCase() + s.slice(1)
const constant = (v: string) => {
  const c = v.replace(/([a-z0-9])([A-Z])/g, "$1_$2").replace(/[^A-Za-z0-9]+/g, "_").replace(/^_|_$/g, "").toUpperCase()
  return /^[0-9]/.test(c) || c === "" ? `V_${c}` : c
}
const esc = (t: string) => t.replace(/\*\//g, "*&#47;").replace(/@/g, "{@literal @}").replace(/[<>]/g, (b) => (b === "<" ? "&lt;" : "&gt;"))
const javaName = (n: string) => (JAVA_KEYWORDS.has(n) ? `${n}Value` : n.replace(/[^A-Za-z0-9]/g, ""))
/** Java class names for tags: Div, H1, Blockquote, Figcaption. */
const className = (tag: string) => up(tag)

function members(t: ts.Type): ts.Type[] {
  return t.isUnion() ? t.types : [t]
}

/** One attribute's Java shape: its setters, and an enum when it is a string union. */
type Attr = { react: string; java: string; doc: string; setters: string[]; enumCode?: string }

function attributeOf(p: ts.Symbol, checker: ts.TypeChecker, C: string, enumNames: Set<string>): Attr | undefined {
  const react = p.name
  if (SKIP.has(react) || react.startsWith("on") && /^on[A-Z]/.test(react)) return undefined
  const java = javaName(react)
  if (TAKEN.has(java)) return undefined
  const doc = ts.displayPartsToString(p.getDocumentationComment(checker)).trim()
  const parts = members(checker.getTypeOfSymbol(p)).filter((t) => !(t.flags & (ts.TypeFlags.Undefined | ts.TypeFlags.Null)))
  const literals = (parts.filter((t) => t.isStringLiteral()) as ts.StringLiteralType[]).filter((l) => l.value !== "")
  const has = (f: ts.TypeFlags) => parts.some((t) => t.flags & f && !t.isStringLiteral())
  const anyText = parts.some((t) => (t.flags & ts.TypeFlags.String) || (t.isIntersection() && t.types.some((x) => x.flags & ts.TypeFlags.String)))
  const number = has(ts.TypeFlags.Number)
  const bool = parts.some((t) => t.flags & ts.TypeFlags.BooleanLiteral)
  const array = parts.some((t) => checker.isArrayType(t) || checker.isTupleType(t))
  const isUrl = URLS.has(react)
  const set = (type: string, value: string) => `        public ${C} ${java}(${type} ${java}) { return attribute("${react}", ${value}); }`
  const setters: string[] = []
  let enumCode: string | undefined
  if (literals.length >= 2 && !isUrl) {
    let E = up(java)
    if (enumNames.has(E) || E === C) E = `${E}Value`
    enumNames.add(E)
    const uniq = [...new Map(literals.map((l) => [constant(l.value), l.value])).entries()]
    enumCode =
      `        /** {@code ${react}}'s words. */\n        public enum ${E} {\n` +
      uniq.map(([k, v]) => `            ${k}("${v}")`).join(",\n") +
      `;\n            final String word;\n            ${E}(String word) { this.word = word; }\n        }`
    setters.push(set(E, `${java} == null ? null : ${java}.word`))
  }
  if (anyText || (literals.length === 1 && !bool)) setters.push(set("String", isUrl ? `${java} == null ? null : url(${java})` : java))
  if (number) setters.push(set("double", java))
  if (bool) {
    setters.push(set("boolean", java))
    // a flag that is usually just on: input.required(), details.open()
    if (!literals.length && !anyText && !number) setters.push(`        public ${C} ${java}() { return ${java}(true); }`)
  }
  if (array && !anyText) setters.push(`        public ${C} ${java}(String... ${java}) { return attribute("${react}", java.util.List.of(${java})); }`)
  if (!setters.length) return undefined
  return { react, java, doc, setters, enumCode }
}

function main() {
  const check = process.argv.includes("--check")
  const parsed = ts.getParsedCommandLineOfConfigFile(path.join(UI, "tsconfig.json"), {}, {
    ...ts.sys,
    onUnRecoverableConfigFileDiagnostic: (d) => fail(ts.flattenDiagnosticMessageText(d.messageText, "\n")),
  })!
  // React's types, reached the way an app reaches them
  const probe = path.join(UI, "src/__html-gen-probe.ts")
  const host = ts.createCompilerHost(parsed.options)
  const read = host.readFile
  host.readFile = (f) => (path.resolve(f) === probe ? `import type * as React from "react"\nexport type Elements = React.JSX.IntrinsicElements\n` : read(f))
  const fileExists = host.fileExists
  host.fileExists = (f) => path.resolve(f) === probe || fileExists(f)
  const prog = ts.createProgram([probe], parsed.options, host)
  const checker = prog.getTypeChecker()
  const file = prog.getSourceFile(probe) ?? fail("cannot read React's types")
  const alias = checker.getExportsOfModule(checker.getSymbolAtLocation(file)!).find((s) => s.name === "Elements")!
  const elements = checker.getDeclaredTypeOfSymbol(alias)

  const classes: string[] = []
  const factories: string[] = []
  const tags: string[] = []
  const report = { left: [] as string[], deprecated: [] as string[] }
  for (const el of checker.getPropertiesOfType(elements).sort((a, b) => a.name.localeCompare(b.name))) {
    const tag = el.name
    const propsType = checker.getTypeOfSymbol(el)
    // the HTML ones: DetailedHTMLProps<...HTMLAttributes<HTMLxElement>, ...> (SVG's are SVGProps)
    if (!/DetailedHTMLProps/.test(checker.typeToString(propsType))) continue
    if (DEPRECATED.has(tag)) { report.deprecated.push(tag); continue }
    if (LEFT_OUT[tag]) { report.left.push(`${tag} (${LEFT_OUT[tag]})`); continue }
    const C = className(tag)
    const enumNames = new Set<string>()
    const attrs = checker
      .getPropertiesOfType(propsType)
      .filter((p) => {
        const parent = p.declarations?.[0]?.parent
        return parent && ts.isInterfaceDeclaration(parent) && !NOT_OWN.has(parent.name.text)
      })
      .sort((a, b) => a.name.localeCompare(b.name))
      .map((p) => attributeOf(p, checker, C, enumNames))
      .filter((a): a is Attr => !!a)
    const element = checker.typeToString(propsType).match(/HTML\w*Element/)?.[0] ?? "HTMLElement"
    tags.push(tag)
    const body = [
      ...attrs.filter((a) => a.enumCode).map((a) => a.enumCode!),
      ...attrs.map((a) => (a.doc ? `        /** ${esc(a.doc).split("\n")[0]} */\n` : "") + a.setters.join("\n")),
    ]
    classes.push(
      `    /** {@code <${tag}>} ({@code ${element}}): <a href="https://developer.mozilla.org/en-US/docs/Web/HTML/Reference/Elements/${tag}">MDN</a>. */\n` +
        `    public static final class ${C} extends HtmlElement<${C}> {\n        ${C}() { super("${tag}"); }\n` +
        (body.length ? `\n${body.join("\n\n")}\n` : "") +
        `    }`
    )
    const m = JAVA_KEYWORDS.has(tag) ? `${tag}Element` : tag
    factories.push(
      VOID.has(tag)
        ? `    /** {@code <${tag}>}. */\n    public static ${C} ${m}() { return new ${C}(); }`
        : `    /** {@code <${tag}>} holding these. */\n    public static ${C} ${m}(Component<?>... children) { return new ${C}().with(children); }\n` +
            `    /** {@code <${tag}>} holding this text. */\n    public static ${C} ${m}(String text) { return new ${C}().text(text); }`
    )
  }

  const java = `${HEADER} from React's types (@types/react): do not edit.
// Run \`bun run html-gen\` in core/src/main/ui after React's types change.
package io.joshuasalcedo.webview4j.ui;

/**
 * HTML's elements for Java screens, each typed with its own attributes: {@code Html.div(Html.p("Paid"))},
 * {@code Html.input().type(Html.Input.Type.EMAIL).required()}, {@code Html.a("Docs").href("https://...")}. They
 * sit beside the kit's components and hold them; every one has HTML's global attributes, a style and classes
 * ({@link Component}), and Java events ({@link HtmlElement}).
 *
 * <p>Left out: deprecated and non-standard elements (${report.deprecated.join(", ")}); ${report.left.join(", ")}.
 */
public final class Html {

    private Html() {}

    /** Text inside an element: {@code Html.p(Html.text("Paid on "), Html.strong("Monday"))}. */
    public static final class Text extends Component<Text> {
        Text(String text) {
            super("htmlText");
            prop("text", java.util.Objects.requireNonNull(text, "text"));
        }
    }

    /** Text inside an element. */
    public static Text text(String text) { return new Text(text); }

${factories.join("\n\n")}

${classes.join("\n\n")}
}
`
  const tagsTs = `${HEADER} from React's types: do not edit. Run \`bun run html-gen\`.
/** The HTML elements a Java screen may hold (Html.java); any other tag is refused. */
export const htmlTags: ReadonlySet<string> = new Set(${JSON.stringify(tags)})
/** The ones that hold nothing. */
export const voidTags: ReadonlySet<string> = new Set(${JSON.stringify([...VOID])})
`
  const outputs: [string, string][] = [[HTML_JAVA, java], [TAGS_TS, tagsTs]]
  for (const [f] of outputs) if (fs.existsSync(f) && !fs.readFileSync(f, "utf8").startsWith(HEADER)) fail(`${f} is hand-written`)
  const differ = outputs.filter(([f, t]) => !fs.existsSync(f) || fs.readFileSync(f, "utf8") !== t)
  if (check) {
    if (differ.length) fail(`out of date: ${differ.map(([f]) => path.basename(f)).join(", ")}; run \`bun run html-gen\``)
    console.log(`html-gen: ${tags.length} elements up to date`)
    return
  }
  for (const [f, t] of differ) fs.writeFileSync(f, t)
  console.log(`html-gen: ${tags.length} elements (${tags.join(" ")})`)
  console.log(`  left out, deprecated: ${report.deprecated.join(" ")}`)
  console.log(`  left out on purpose: ${report.left.join("; ")}`)
}

main()
