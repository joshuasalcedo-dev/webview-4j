// icon-gen: Lucide's icons (lucide-react, the kit's icon set), typed for Java. It writes one enum, Icon, of every
// icon Lucide has (its own names, not their old aliases), into build/generated/sources/icons (or ICON_GEN_OUT).
// Gradle runs it before compiling (:core:uiIconGen). A component's icon(Icon) sends "lucide:<name>", which the
// kit's NamedIcon draws.
import { mkdirSync, rmSync, writeFileSync } from "node:fs"
import { dirname, join, resolve } from "node:path"
import dynamicIconImports from "lucide-react/dynamicIconImports"
import * as lucide from "lucide-react"
const { icons } = lucide

const here = dirname(new URL(import.meta.url).pathname.replace(/^\/([A-Za-z]:)/, "$1"))
const out = process.env.ICON_GEN_OUT ?? resolve(here, "../../../../build/generated/sources/icons/java")
const PACKAGE = "io.joshuasalcedo.webview4j.ui.icons"

const pascal = (kebab: string) => kebab.split("-").map((p) => p.charAt(0).toUpperCase() + p.slice(1)).join("")
const constant = (kebab: string) => {
  const c = kebab.toUpperCase().replace(/-/g, "_")
  return /^[0-9]/.test(c) ? `_${c}` : c
}

// Every name Lucide answers to: its own (in its icon map) and its older ones (aliases, still exported), each alias
// told which icon it draws
const exported = lucide as unknown as Record<string, unknown>
const ownByComponent = new Map<unknown, string>()
for (const kebab of Object.keys(dynamicIconImports)) if (pascal(kebab) in icons) ownByComponent.set(exported[pascal(kebab)], kebab)
const names = Object.keys(dynamicIconImports)
  .filter((kebab) => exported[pascal(kebab)] !== undefined)
  .sort()
const aliasOf = (kebab: string) => (pascal(kebab) in icons ? undefined : ownByComponent.get(exported[pascal(kebab)]))
if (names.length < 1000) {
  console.error(`icon-gen: only ${names.length} icons found in lucide-react: is it installed?`)
  process.exit(1)
}
const seen = new Set<string>()
for (const n of names) {
  const c = constant(n)
  if (seen.has(c)) {
    console.error(`icon-gen: two icons make ${c}`)
    process.exit(1)
  }
  seen.add(c)
}

const version = (await import("lucide-react/package.json", { with: { type: "json" } })).default.version as string
const code = `// Generated by core/src/main/ui/scripts/icon-gen.ts from lucide-react ${version}: do not edit.
package ${PACKAGE};

/**
 * An icon from Lucide (https://lucide.dev, ISC licence), the kit's icon set: ${names.length} of them, line icons
 * that follow the text's colour. {@code button.icon(Icon.SHOPPING_CART)}, {@code new IconView(Icon.STAR)}.
 */
public enum Icon {
${names.map((n) => `    /** {@code ${n}}${aliasOf(n) ? `: Lucide's older name for {@link #${constant(aliasOf(n)!)}}` : ""}. */\n    ${constant(n)}("${n}")`).join(",\n")};

    private final String name;

    Icon(String name) {
        this.name = name;
    }

    /** Lucide's name for it ({@code "shopping-cart"}). */
    public String lucideName() {
        return name;
    }

    /** What the page draws it by: {@code "lucide:shopping-cart"}. */
    public String key() {
        return "lucide:" + name;
    }
}
`
const dir = join(out, ...PACKAGE.split("."))
rmSync(dir, { recursive: true, force: true })
mkdirSync(dir, { recursive: true })
writeFileSync(join(dir, "Icon.java"), code)
console.log(`icon-gen: ${names.length} Lucide icons (lucide-react ${version}) into ${dir}`)
