// style-gen: the kit's CSS, typed for Java. For each component of style-gen.json it writes an enum of the classes
// under the component's CSS roots (.nt-dialog, .nt-dialog-title...), <Java>Part implements StylePart<Java>, into
// build/generated/sources/style (or STYLE_GEN_OUT). Gradle runs it before compiling (:core:uiStyleGen). It only
// reads the CSS: it never writes into src, and never into a style file.
//
// It stops with an error when a root is in no CSS file, or a Java class it names does not exist: the CSS and the
// components stay in step.
import { existsSync, mkdirSync, readFileSync, readdirSync, rmSync, statSync, writeFileSync } from "node:fs"
import { dirname, join, resolve } from "node:path"

const here = dirname(new URL(import.meta.url).pathname.replace(/^\/([A-Za-z]:)/, "$1"))
const ui = resolve(here, "..")
const javaComponents = resolve(ui, "../java/io/joshuasalcedo/webview4j/ui/components")
const out = process.env.STYLE_GEN_OUT ?? resolve(ui, "../../../build/generated/sources/style/java")
const PACKAGE = "io.joshuasalcedo.webview4j.ui.style"

type Entry = { java: string; roots: string[] }

function fail(message: string): never {
  console.error(`style-gen: ${message}`)
  process.exit(1)
}

function cssFiles(dir: string): string[] {
  const files: string[] = []
  for (const name of readdirSync(dir)) {
    if (name === "node_modules" || name === "egui4j" || name === "grammar") continue
    const path = join(dir, name)
    if (statSync(path).isDirectory()) files.push(...cssFiles(path))
    else if (name.endsWith(".css")) files.push(path)
  }
  return files.sort()
}

/** Every class of the kit (nt-...) in its CSS, with the file it is first in. */
function kitClasses(): Map<string, string> {
  const classes = new Map<string, string>()
  for (const file of cssFiles(join(ui, "src"))) {
    const css = readFileSync(file, "utf8").replace(/\/\*[\s\S]*?\*\//g, "")
    for (const m of css.matchAll(/\.(nt-[a-z0-9]+(?:-[a-z0-9]+)*)/g)) {
      if (m[1].startsWith("nt-s-")) continue // the renderer's own state classes
      if (!classes.has(m[1])) classes.set(m[1], file.slice(ui.length + 1).replaceAll("\\", "/"))
    }
  }
  return classes
}

function constant(name: string): string {
  const c = name.toUpperCase().replace(/-/g, "_")
  return /^[0-9]/.test(c) ? `_${c}` : c
}

function enumFor(entry: Entry, classes: Map<string, string>): { name: string; code: string } {
  const simple = entry.java.split(".").pop()!
  // a plugin's class (plugin.chat.MessageBubble) is under webview4j itself; the rest under ui.components
  const inPlugin = entry.java.startsWith("plugin.")
  const fqcn = inPlugin ? `io.joshuasalcedo.webview4j.${entry.java}` : `io.joshuasalcedo.webview4j.ui.components.${entry.java}`
  const file = inPlugin ? join(javaComponents, "../..", ...entry.java.split(".")) + ".java" : join(javaComponents, ...entry.java.split(".")) + ".java"
  if (!existsSync(file)) fail(`${entry.java}: no such class (${file})`)
  const [own, ...others] = entry.roots
  const parts = new Map<string, string>() // constant -> class
  for (const root of entry.roots) {
    if (!classes.has(root)) fail(`${entry.java}: the root .${root} is in no CSS file`)
    const under = [...classes.keys()].filter((c) => c === root || c.startsWith(root + "-")).sort()
    for (const c of under) {
      // a class under a longer root of another component is not this one's (nt-field-hint is the field's, not
      // nt-file's); here every root's classes are its own, the first root's without a prefix
      const name =
        c === own ? "ROOT"
        : root === own ? constant(c.slice(own.length + 1))
        : c === root ? constant(root.slice(3))
        : constant(`${root.slice(3)}-${c.slice(root.length + 1)}`)
      if (parts.has(name) && parts.get(name) !== c) fail(`${entry.java}: ${name} is both .${parts.get(name)} and .${c}`)
      parts.set(name, c)
    }
  }
  const name = `${simple}Part`
  const constants = [...parts.entries()]
    .sort(([a], [b]) => (a === "ROOT" ? -1 : b === "ROOT" ? 1 : a.localeCompare(b)))
    .map(([k, c]) => `    /** {@code .${c}} (${classes.get(c)}). */\n    ${k}("${c}")`)
  const code = `// Generated by core/src/main/ui/scripts/style-gen.ts from the kit's CSS and style-gen.json: do not edit.
package ${PACKAGE};

import io.joshuasalcedo.webview4j.ui.StylePart;

/**
 * The parts of {@link ${fqcn}} as the kit's CSS draws them${others.length ? ` (.${own}, ${others.map((o) => `.${o}`).join(", ")})` : ` (.${own})`}:
 * {@code ${simple.charAt(0).toLowerCase() + simple.slice(1)}.style(${name}.ROOT, Style.of()...)}.
 */
public enum ${name} implements StylePart<${fqcn}> {
${constants.join(",\n")};

    private final String className;

    ${name}(String className) {
        this.className = className;
    }

    @Override
    public String className() {
        return className;
    }
}
`
  return { name, code }
}

function main() {
  const config = JSON.parse(readFileSync(join(ui, "style-gen.json"), "utf8")) as { components: Entry[] }
  const classes = kitClasses()
  const dir = join(out, ...PACKAGE.split("."))
  rmSync(dir, { recursive: true, force: true })
  mkdirSync(dir, { recursive: true })
  const seen = new Set<string>()
  for (const entry of config.components) {
    if (seen.has(entry.java)) fail(`${entry.java} is in style-gen.json twice`)
    seen.add(entry.java)
    const { name, code } = enumFor(entry, classes)
    writeFileSync(join(dir, `${name}.java`), code)
  }
  writeFileSync(
    join(dir, "package-info.java"),
    `// Generated by core/src/main/ui/scripts/style-gen.ts: do not edit.
/**
 * The components' parts, typed, made from the kit's CSS when core is built: one enum per component
 * ({@code ButtonPart}, {@code DialogPart}...), each a {@link io.joshuasalcedo.webview4j.ui.StylePart} of its
 * component only. {@code component.style(Part.X, Style.of()...)} styles a part of one component;
 * {@code new StyleSheet().rule(Part.X, ...)} every one in the window.
 */
package ${PACKAGE};
`
  )
  console.log(`style-gen: ${config.components.length} components, ${classes.size} classes in the CSS, into ${dir}`)
}

main()
